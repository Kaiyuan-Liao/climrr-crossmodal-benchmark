#!/usr/bin/env python3
"""M4-WP4r1 Phase D: render `docs/LITERATURE_WP4_READING.md` from the tracked records.

Every number, status and quotation comes from `artifacts/literature/wp4_sample.json`,
`wp4_claims_summary.json`, `wp4_claims/*.json`, `wp4_hit_classification.json` and
`wp4_claim_screens.json`; nothing is typed by hand. No timestamp, so a re-run
reproduces the document byte for byte.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr.checksums import sha256_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

LIT = REPO_ROOT / "artifacts" / "literature"
OUT = REPO_ROOT / "docs" / "LITERATURE_WP4_READING.md"
DIMENSIONS = ("concept", "relation_or_direction", "geography", "temporal_frame", "scenario",
              "experimental_condition")
STATEMENT = ("deterministic rank sample of lexical place candidates from LITCORPUS-02; "
             "not representative of the corpus or the literature")


def load(name: str) -> dict:
    return json.loads((LIT / name).read_text(encoding="utf-8"))


def span(b: dict) -> str:
    return f"`{b['json_path']}` [{b['char_start']}, {b['char_end']}): “{b['evidence_text']}”"


def short(text: str, n: int = 70) -> str:
    text = text.replace("|", "\\|")
    return text if len(text) <= n else text[: n - 1] + "…"


def render() -> str:
    sample, summary = load("wp4_sample.json"), load("wp4_claims_summary.json")
    hits, screens = load("wp4_hit_classification.json"), load("wp4_claim_screens.json")
    records = [load(f"wp4_claims/{s['lit2_id']}.json") for s in sample["selected"]]
    hit_by = {it["lit2_id"]: it for it in hits["items"]}
    t, ht, st = summary["totals"], hits["totals"], screens["totals"]
    L: list[str] = []
    a = L.append
    a("# M4-WP4 --- reader-1 reading of the 20-paper candidate sample")
    a("")
    a("*Generated by `scripts/render_wp4_reading.py` from the tracked records in")
    a("`artifacts/literature/`. Do not edit by hand.*")
    a("")
    a(f"> **The sample is a {STATEMENT}.**")
    a("")
    a("This is **reader 1's view only** (D-025, Track A). The blind second reading, the")
    a("comparison, adjudication and evidence tiers, and compatibility with the ClimRR")
    a("prototypes are later steps; none has been run. No lexical retrieval hit is a bridge.")
    a("")
    a(f"Claims are what the papers state, extracted by **manual reading by the EXECUTOR as reader 1**")
    a(f"on {summary['extraction_date']}: each file was verified by SHA-256 against the frozen sample,")
    a("then read completely; no model API, no embedding, no search of other corpus files. The")
    a("WP1/WP2 rubric is unchanged; `geography` additionally records the **role** the place plays.")
    a(f"**Every claim is `single_reader_provisional`, evidence tier `C`** "
      f"({t['by_claim_validation_status']['single_reader_provisional']} of {t['claims']}).")
    a("")
    a("**Order of work.** The reading was committed (`e0857aa`) before any term-hit file")
    a("(`hits.csv`) or place-hit location was opened. Hit precision was classified afterwards")
    a(f"(`{hits['made_after_reading_frozen_at']}` is recorded in `wp4_hit_classification.json`) and changed no claim.")
    a("")
    a("**Prior exposure.** `LIT2-001075` (item `272852900`) is LITCORPUS-00 `LIT-001536`, read")
    a("twice in M4-WP2. It was re-read here from its source bytes; no `artifacts/literature/wp2_*`,")
    a("`docs/LITERATURE_WP2_*`, `docs/M5_WP2_*` or `artifacts/bridges/` file was opened in this package.")
    a("Its record carries `prior_exposure`.")
    a("")
    a("## The sample")
    a("")
    a(f"- Corpus: `{sample['corpus_id']}`; sample SHA-256 `{summary['sample_sha256']}` (frozen before reading, D-025).")
    a("- Rule: fire weather ranks 10, 20, …, 100 and extreme heat ranks 14, 28, …, 140 of the place-candidate lists sorted by LIT2 id; no rank advanced.")
    a(f"- Span integrity: {summary['span_integrity_check']['spans_checked']} spans re-sliced from the decoded source, all exact.")
    a("")
    a("| Item | Arm | Title (as stored) | Scope | Terminal status | Claims | Concept hit | Place hit |")
    a("| --- | --- | --- | --- | --- | ---: | --- | --- |")
    for s, r in zip(sample["selected"], records):
        title = r["bibliographic"]["title"]
        ttl = short(title["value"]) if title["status"] != "unknown" else "*(no title field)*"
        h = hit_by[s["lit2_id"]]
        a(f"| `{s['lit2_id']}` | {s['arm'].replace('_v1', '')} | {ttl} | `{r['scope_status']}` | `{r['terminal_status']}` "
          f"| {len(r['claims'])} | `{h['item_concept_class']}` | `{h['item_place_class']}` |")
    a("")
    a(f"**Totals:** {t['claims']} claims from {t['items_with_claims']} items; "
      f"{t['by_scope_status']['in_scope_hazard']} `in_scope_hazard`, {t['by_scope_status']['ambiguous']} `ambiguous`, "
      f"{t['by_scope_status']['off_topic']} `off_topic`; {t['claims_with_any_inferred_dimension']} claims carry an `inferred` dimension; "
      f"{t['rejected_or_ambiguous']} passages kept as rejected or ambiguous.")
    a("")
    a("The item columns *Concept hit* and *Place hit* give the most substantive class among the item's matched terms; per-term classes follow in each item section.")
    a("")
    a("## Screens over the 83 claims (descriptive; not compatibility)")
    a("")
    a("| Screen | Claims |")
    a("| --- | ---: |")
    a(f"| geography names a US place | {st['us_geography']} ({st['us_geography_explicit']} explicit, {st['us_geography_inferred']} inferred) |")
    for k, v in st["us_geography_by_type"].items():
        a(f"| … of which `{k}` | {v} |")
    a(f"| approved pilot family term in the `concept` value (C-2 terms, masks applied) | {st['pilot_family_term_in_concept']} |")
    for k, v in st["pilot_family_term_in_concept_by_family"].items():
        a(f"| … `{k}` | {v} |")
    a(f"| pilot family term **and** US geography | {st['pilot_family_term_and_us_geography']} |")
    a(f"| `scenario` not `unknown` | {st['scenario_not_unknown']} |")
    a(f"| `scenario` names an RCP / SSP / SRES pathway | {st['scenario_named']} |")
    a("")
    pilot = [c for c in screens["claims"] if c["pilot_family_terms_in_concept"]]
    a("Claims whose concept value holds a pilot family term:")
    a("")
    for c in pilot:
        terms = ", ".join(sorted({h["term"] for h in c["pilot_family_terms_in_concept"]}))
        lid = c["claim_id"].rsplit("-C", 1)[0]
        cls = sorted({p["primary_class"] for p in hit_by[lid]["pairs"]
                      if p["kind"] == "concept" and p["term"].lower() in {h["term"].lower() for h in c["pilot_family_terms_in_concept"]}})
        a(f"- `{c['claim_id']}` ({c['claim_type']}; concept `{c['concept_status']}`) --- “{c['concept']}” [{terms}]; "
          f"geography: {c['geography']} (`{c['geography_status']}`); item hit class for the term: "
          + (", ".join(f"`{x}`" for x in cls) or "*(term not among the item's frozen hits)*") + ".")
    a("")
    a("## Hit precision (after reading)")
    a("")
    a(f"Matcher: {hits['matcher']}. Scope: {hits['scope_of_terms']}. All {ht['frozen_first_hit_rows']} frozen")
    a(f"first-hit rows were reproduced exactly; {ht['occurrences']} occurrences in all were classified.")
    a("")
    a("| Concept class | Item-term pairs | Occurrences | Items |")
    a("| --- | ---: | ---: | ---: |")
    for c in hits["vocabulary"]["concept"]:
        a(f"| `{c}` | {ht['concept_pairs_by_primary_class'][c]} | {ht['concept_occurrences_by_class'][c]} | {ht['items_by_concept_class'][c]} |")
    a("")
    a("| Place class | Item-term pairs | Occurrences | Items |")
    a("| --- | ---: | ---: | ---: |")
    for c in hits["vocabulary"]["place"]:
        a(f"| `{c}` | {ht['place_pairs_by_primary_class'][c]} | {ht['place_occurrences_by_class'][c]} | {ht['items_by_place_class'][c]} |")
    a("")
    a("| Place term | " + " | ".join(f"`{c}`" for c in hits["vocabulary"]["place"]) + " |")
    a("| --- | " + " | ".join("---:" for _ in hits["vocabulary"]["place"]) + " |")
    for term, row in ht["place_pairs_by_term"].items():
        a(f"| `{term}` | " + " | ".join(str(row[c]) for c in hits["vocabulary"]["place"]) + " |")
    a("")
    a("## Item by item")
    for s, r in zip(sample["selected"], records):
        h = hit_by[s["lit2_id"]]
        a("")
        a(f"### `{s['lit2_id']}` (`{s['item_id']}`, {s['arm']} rank {s['rank']}) --- `{r['terminal_status']}`")
        a("")
        if r.get("prior_exposure"):
            a(f"*Prior exposure:* {r['prior_exposure']}.")
            a("")
        b = r["bibliographic"]
        bits = []
        for f in ("title", "authors", "year", "venue"):
            v = b[f]
            bits.append(f"{f}: " + (f"“{v['value']}” (`{v['status']}`)" if v["status"] != "unknown" else "`unknown`"))
        a("Bibliographic --- " + "; ".join(bits) + ".")
        if b.get("note"):
            a(f"*{b['note']}*")
        a("")
        a(f"**Scope: `{r['scope_status']}`.** {r['scope_reason']}  ")
        a(f"Scope evidence: {span(r['scope_evidence'])}")
        for c in r["claims"]:
            a("")
            a(f"**{c['claim_id']}** ({c['claim_type']}; `{c['claim_validation_status']}`, tier {c['evidence_tier']}). {c['claim_text']}")
            a("")
            for d in DIMENSIONS:
                v = c[d]
                line = f"- {d.replace('_', ' ')}: {v['value']} [`{v['status']}`]"
                if d == "geography":
                    line += f" --- role: {v['role']}"
                if "support" in v:
                    line += f" --- support {span(v['support'])}"
                a(line)
            a(f"- evidence: {span(c['evidence'])}")
            if c.get("notes"):
                a(f"- note: {c['notes']}")
        if r["rejected_or_ambiguous"]:
            a("")
            a("Rejected or ambiguous:")
            a("")
            for x in r["rejected_or_ambiguous"]:
                a(f"- **{x['candidate_id']}** {span(x['evidence'])} --- {x['reason']}")
        if r.get("notes"):
            a("")
            a(f"*Item note:* {r['notes']}")
        a("")
        a("Hit precision:")
        a("")
        for p in h["pairs"]:
            counts = ", ".join(f"{k} {v}" for k, v in p["class_counts"].items())
            inside = ", ".join(p["occurs_inside_promoted_claim_evidence"]) or "none"
            a(f"- {p['kind']} `{p['term']}` --- **`{p['primary_class']}`** ({p['n_occurrences']} occurrence(s): {counts}). "
              f"{p['reason']} Inside a promoted claim's evidence span: {inside}.")
    a("")
    return "\n".join(L)


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    rec = write_run_record(
        "render_wp4_reading",
        result_summary={"doc_sha256": sha256_file(OUT),
                        "claims_summary_sha256": sha256_file(LIT / "wp4_claims_summary.json"),
                        "hit_classification_sha256": sha256_file(LIT / "wp4_hit_classification.json"),
                        "claim_screens_sha256": sha256_file(LIT / "wp4_claim_screens.json")},
        passed=True,
        data_path=LIT / "wp4_sample.json",
        output_path=OUT,
    )
    print(f"Wrote {repo_relative(OUT)}; run record {repo_relative(rec)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
