#!/usr/bin/env python3
"""M5-WP4 step 2: run every adjudicated WP4 claim against the three prototypes, from the frozen inputs.

Verifies `artifacts/bridges/m5wp4_inputs.json` first (fail closed), then writes
`m5wp4_matrix.json`, `m5wp4_matrix.csv` and `docs/M5_WP4_COMPATIBILITY.md`,
once; a later run verifies byte equality. No QA.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr import compat, conceptmap, m5wp2, m5wp4  # noqa: E402
from climrr.checksums import sha256_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

DOC = REPO_ROOT / "docs" / "M5_WP4_COMPATIBILITY.md"
LABELS = {"P-CELL-1": "cell R106C361 (fire weather, summer)", "P-COUNTY-1": "Oklahoma, Stephens (fire weather, summer)",
          "P-STATE-1": "California (heat index, days above 105 °F; v2)"}
PLACES = ("California", "Oklahoma", "Stephens")
#: A named emissions / climate scenario label in a scenario value (descriptive count only; S-1 reads RCP alone).
NAMED_SCENARIO = re.compile(r"\b(RCP\s*\d(?:\.\d)?|SSP\s*\d(?:-\d(?:\.\d)?)?|SRES\s*[AB]\d\w*)\b", re.IGNORECASE)


def _write(path: Path, text: str) -> str:
    if path.exists():
        if path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"FAIL: {repo_relative(path)} differs from a rebuild")
        return "verified"
    path.write_text(text, encoding="utf-8")
    return "written"


def _md(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def scenario_screen(rows: list[dict]) -> dict:
    per_claim = {}
    for r in rows:
        sc = r["judgments"]["scenario"]["claim_value"]
        per_claim[r["claim_id"]] = (sc.get("raw"), sc.get("tag"))
    not_unknown = {k: v for k, v in per_claim.items() if v[1] != "unknown" and v[0] not in (None, "unknown")}
    named = {k: v for k, v in not_unknown.items() if NAMED_SCENARIO.search(str(v[0]))}
    return {"n_claims": len(per_claim), "not_unknown": {k: list(v) for k, v in not_unknown.items()},
            "named": {k: list(v) for k, v in named.items()},
            "rule": "named = an RCP / SSP / SRES label in the effective scenario value; the scenario dimension only"}


def render(rows: list[dict], summ: dict, frozen: dict, scen: dict) -> str:
    n_elig = summ["n_candidate_bridge_eligible"]
    L = ["# M5-WP4 --- positive-case compatibility run on LITCORPUS-02", "",
         "**Generated by `scripts/m5wp4_matrix.py` from `artifacts/bridges/m5wp4_inputs.json`; do not edit by hand.** "
         "Every adjudicated claim of the twenty frozen LITCORPUS-02 place candidates (all evidence tiers, tier carried) against "
         "P-CELL-1, P-COUNTY-1 and **P-STATE-1 v2**. Rules: C-1 / C-2 with the D-025 concept map (`approved_lexical` forms "
         "participate; `approved_family_term` excluded and masking --- the \"extended heat index\" mask); G-1 / G-2 / G-3 with "
         "**G-R** (the geography role); T-1 / T-2 / T-3; S-1; D-1; U-1. Deterministic rules only; no similarity, no model "
         "judgement. **No QA.** The M5-WP1 and M5-WP2 freezes are untouched; `compat.py` is unchanged.", "",
         f"Inputs `{sha256_file(m5wp4.INPUTS_PATH)[:8]}…`; concept map `{frozen['concept_map_sha256'][:8]}…`; "
         f"R-FWI-1 {frozen['r_fwi_1_version']['version']} (recorded; it governs retrieval, not compatibility).", "",
         f"**{summ['n_pairs']} pairs** ({frozen['n_claims']} claims × {frozen['n_prototypes']} prototypes; claims by tier "
         + ", ".join(f"{t} {sum(c['evidence_tier'] == t for c in frozen['claims'])}" for t in "ABC")
         + f"). Candidate-bridge-eligible: **{n_elig}**.", ""]
    if n_elig == 0:
        L += [f"> {m5wp4.BOUNDED_SENTENCE}", ""]
        L += ["**GUIDANCE, D-027 (2026-10-20): PASS WITH ACTIONS --- bounded zero accepted.** The sentence above is the "
              "accepted bounded statement, verbatim. **Do not generalize beyond the tested sample**: these adjudicated claims "
              "of these twenty frozen papers, against these three prototypes, under these rules. It is not evidence that "
              "cross-modal bridges are impossible. The ruling's prospective changes --- the C-2 mask for "
              "\"standardized heat index\" and the mixed-region G-2 semantics (`docs/BRIDGE_ELIGIBILITY.md` §8) --- apply "
              "to future runs only; **this matrix is not rewritten** and its rows are unchanged.", ""]
    L += ["## Per-dimension counts", "", "| Dimension | compatible | compatible_at_family_level | incompatible | not_evaluable |",
          "| --- | ---: | ---: | ---: | ---: |"]
    for d, v in summ["per_dimension"].items():
        L.append(f"| {d} | {v.get('compatible', 0)} | {v.get(compat.FAMILY_LEVEL, 0)} | {v.get('incompatible', 0)} | {v.get('not_evaluable', 0)} |")
    L += ["", "Provisional relations: " + ", ".join(f"`{k}` {v}" for k, v in summ["relations"].items()) + ".",
          f"Incompatible by rule: {summ['incompatible_by_rule'] or 'none'}.", ""]
    elig = [r for r in rows if r["candidate_bridge_eligible"]]
    if elig:
        L += ["## Eligible pairs", ""]
        for r in elig:
            g = r["judgments"]["geography"]["claim_value"]
            L += [f"### {r['pair_id']} (tier {r['evidence_tier']}; relation `{r['provisional_relation']}`)", "",
                  f"Claim: {_md(r['claim_text'])}",
                  f"Evidence `{r['evidence']['json_path']}` [{r['evidence']['char_start']}, {r['evidence']['char_end']}): \"{_md(r['evidence']['evidence_text'])}\"",
                  f"Geography: {_md(g.get('raw'))} [{g.get('tag')}], role {_md(g.get('role'))} ({g.get('role_class')}); "
                  f"not_evaluable: {', '.join(r['not_evaluable_dimensions']) or 'none'}", ""]
            L += [f"- {d}: **{j['status']}** ({j['rule_id']}, {j['reason']})" for d, j in r["judgments"].items()]
            L.append("")
        if any(r["evidence_tier"] == "C" for r in elig):
            L += [f"> {m5wp4.TIER_C_SENTENCE}", ""]
    pos = [r for r in rows if r["judgments"]["concept"]["status"] != "not_evaluable"]
    L += ["## Pairs with a positive concept judgment", "",
          "C-2 is lexical: an approved family term inside the claim's concept value gives `compatible_at_family_level`, never "
          "metric equality.", "",
          "| Pair | Tier | Concept (rule) | Matched term → family (decision) | Geography [tag], role class | Time | Scenario | Direction | Relation | Flags |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in pos:
        j = r["judgments"]
        fm = j["concept"]["claim_value"].get("family_match", {})
        g = j["geography"]
        L.append(f"| {r['pair_id']} | {r['evidence_tier']} | {j['concept']['status']} ({j['concept']['rule_id']}) | "
                 f"\"{fm.get('matched_text', '')}\" [{fm.get('char_start')}, {fm.get('char_end')}) → {fm.get('family')} ({fm.get('concept_map_decision_id')}) | "
                 f"{_md(g['claim_value'].get('raw'))} [{g['claim_value'].get('tag')}], {g['claim_value'].get('role_class')}: {g['status']} ({g['rule_id']}) | "
                 + " | ".join(f"{j[d]['status']} ({j[d]['rule_id']})" for d in ("time", "scenario", "direction"))
                 + f" | `{r['provisional_relation']}` | {'; '.join(r['flags']) or '---'} |")
    coll = [r for r in rows if m5wp4.COLLISION_FLAG in r["flags"]]
    L += ["", "## Collision list for GUIDANCE --- \"standardized heat index\"", "",
          "C-2 matches `heat index` inside \"standardized heat index\". As ordered, **no mask was added**; every such match is "
          f"recorded with the flag `{m5wp4.COLLISION_FLAG}`. D-027 adds the mask **prospectively** (future runs); the "
          "rows below are as frozen.", ""]
    if coll:
        L += ["| Pair | Tier | Concept value | Hit [start, end) | Concept judgment | Relation |", "| --- | --- | --- | --- | --- | --- |"]
        for r in coll:
            cj = r["judgments"]["concept"]
            hs = ", ".join(f"\"{h['matched_text']}\" [{h['char_start']}, {h['char_end']})" for h in cj["possible_collision"]["hits"])
            L.append(f"| {r['pair_id']} | {r['evidence_tier']} | {_md(cj['claim_value']['raw'])} | {hs} | {cj['status']} ({cj['rule_id']}) | `{r['provisional_relation']}` |")
    else:
        L.append("No C-2 hit fell inside \"standardized heat index\".")
    L += ["", "## Geography: label and role", "",
          "G-1 is exact equality of an `explicit` claim geography with the prototype label (`R106C361`; `Oklahoma, Stephens`; "
          "`California`). **G-R** adds the role: a place whose role class is `affiliation` or `citation_or_person` is "
          "`not_evaluable` (role not study geography), never compatible; an exact label match is `compatible` only for role "
          "class `study_area` or `cited_study_area`, otherwise `not_evaluable`. A state name against a county prototype of that "
          "state is `not_evaluable` (`different_granularity_state_vs_county`).", "",
          "### Every pair whose geography names California, Oklahoma or Stephens", "",
          "| Pair | Tier | Claim geography [tag] | Role (class) | Prototype label | Judgment | Why |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        g = r["judgments"]["geography"]
        raw = str(g["claim_value"].get("raw"))
        if any(conceptmap.find_term(p, raw) for p in PLACES):
            L.append(f"| {r['pair_id']} | {r['evidence_tier']} | {_md(raw)} [{g['claim_value'].get('tag')}] | "
                     f"{_md(g['claim_value'].get('role'))} ({g['claim_value'].get('role_class')}) | {_md(g['prototype_value']['label'])} | "
                     f"{g['status']} ({g['rule_id']}) | {g['reason']} |")
    gran = [r for r in rows if r["judgments"]["geography"]["rule_id"] == "G-3-granularity"]
    L += ["", "Readings of these rows: `California` with role class `study_area` or `cited_study_area` against P-STATE-1 is "
          "`compatible` (G-1); `California` with role class `contextual` against P-STATE-1 is `not_evaluable` (G-R); a list "
          "of states, a county, a city, or a part of a state is not the label and stays `not_evaluable` (G-3); an `inferred` "
          "geography never reaches G-1. "
          + (f"Granularity cases: {', '.join(r['pair_id'] for r in gran)}." if gran else
             "**No claim's geography is the bare state name `Oklahoma`**, so the state-vs-county granularity reason did not "
             "fire on real data; it and the role gate are tested on synthetic claims (`tests/test_m5wp4.py`)."), "",
          "**G-2 list.** Only the committed M5-WP1 list is used. Places outside the United States that are not on it give "
          "`not_evaluable`, not `incompatible`. Extending the list was not authorized here.", "",
          "## Incompatible pairs", "", "| Pair | Tier | Rule | Claim value | Reason |", "| --- | --- | --- | --- | --- |"]
    for r in rows:
        for d, j in r["judgments"].items():
            if j["status"] == "incompatible":
                L.append(f"| {r['pair_id']} | {r['evidence_tier']} | {j['rule_id']} | {_md(j['claim_value'].get('raw'))} | {j['reason']} |")
    L += ["", "## Per prototype", "", "| Prototype | concept + | geography compatible | incompatible pairs | related_insufficient | uncertain |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for pid in ("P-CELL-1", "P-COUNTY-1", "P-STATE-1"):
        pr = [r for r in rows if r["prototype_id"] == pid]
        L.append(f"| {pid} --- {LABELS[pid]} | {sum(r['judgments']['concept']['status'] != 'not_evaluable' for r in pr)} | "
                 f"{sum(r['judgments']['geography']['status'] == 'compatible' for r in pr)} | {sum(r['n_incompatible'] > 0 for r in pr)} | "
                 f"{sum(r['provisional_relation'] == 'related_insufficient' for r in pr)} | {sum(r['provisional_relation'] == 'uncertain' for r in pr)} |")
    L += ["", "## Scenario", "",
          f"Claims whose effective scenario is not `unknown`: **{len(scen['not_unknown'])}** of {scen['n_claims']}"
          + (" (" + "; ".join(f"{k}: \"{_md(v[0])}\" [{v[1]}]" for k, v in scen["not_unknown"].items()) + ")" if scen["not_unknown"] else "")
          + f". **Named scenario (RCP / SSP / SRES label): {len(scen['named'])}.** S-1 is therefore `not_evaluable` on every pair.", "",
          "## Rules added for this run", ""]
    L += [f"- **{k}**: {v}." for k, v in m5wp4.M5WP4_RULES.items()]
    L += ["", "Relation rules, in precedence (as M5-WP2): " + "; ".join(f"`{k}`: {v}" for k, v in m5wp2.RELATION_RULES.items()) + ".", ""]
    return "\n".join(L) + "\n"


def main() -> int:
    try:
        frozen = m5wp4.verify_inputs()
    except m5wp4.FreezeError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    rows = m5wp4.run(frozen)
    if len(rows) != frozen["n_pairs"] or len({r["pair_id"] for r in rows}) != len(rows):
        print("FAIL: not every frozen pair evaluated exactly once", file=sys.stderr)
        return 1
    summ = m5wp4.summarize(rows)
    scen = scenario_screen(rows)
    out = {"package": frozen["package"], "inputs_sha256": sha256_file(m5wp4.INPUTS_PATH), "rules": compat.ALL_RULES,
           "m5wp4_rules": m5wp4.M5WP4_RULES, "relation_rules": m5wp2.RELATION_RULES, "summary": summ,
           "scenario_screen": scen, "rows": rows,
           "bounded_conclusion": m5wp4.BOUNDED_SENTENCE if summ["n_candidate_bridge_eligible"] == 0 else None}
    acts = {"json": _write(m5wp4.MATRIX_JSON, json.dumps(out, indent=2, ensure_ascii=False) + "\n"),
            "csv": _write(m5wp4.MATRIX_CSV, m5wp4.to_csv(rows)),
            "doc": _write(DOC, render(rows, summ, frozen, scen))}
    print(f"  pairs {summ['n_pairs']}; eligible {summ['n_candidate_bridge_eligible']}; relations {summ['relations']}; {acts}")
    for d, v in summ["per_dimension"].items():
        print(f"   {d}: {v}")
    print(f"  collisions {summ['possible_collision_pair_ids']}; named scenario {len(scen['named'])}")
    rec = write_run_record("m5wp4_matrix", result_summary={"actions": acts, "summary": {k: summ[k] for k in
                           ("n_pairs", "n_candidate_bridge_eligible", "relations", "per_dimension", "incompatible_by_rule",
                            "possible_collision_pair_ids")}, "named_scenario": len(scen["named"])},
                           passed=True, data_path=m5wp4.INPUTS_PATH, output_path=m5wp4.MATRIX_JSON,
                           config_snapshot={"inputs_sha256": sha256_file(m5wp4.INPUTS_PATH)})
    print(f"Run record: {repo_relative(rec)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
