#!/usr/bin/env python3
"""M4-WP0 Phase D: query-scope coverage --- the pilot's vocabulary against the collection query.

Inputs:

- `data/metadata/literature_query.txt`, verified against `data/manifest.json`
  and re-parsed here; `artifacts/literature/query_parsed.json` must agree with
  the re-parse or the run fails as stale;
- `literature_probe.concept_terms` from the three prototype records in
  `artifacts/phenomena/prototypes/`;
- the four pilot-family names, verbatim from the headings of
  `docs/PILOT_SUBSET.md`.

Outputs: `artifacts/literature/query_scope_coverage.json` and the generated
`docs/LITERATURE_QUERY_SCOPE.md`. Neither carries a timestamp, so a re-run on
the same inputs reproduces both byte for byte.

**This compares strings with strings.** Every result is about the query ---
which strings it contains --- and none is about any paper. The classification
rule and the reason the fourth category cannot be emitted are in
`climrr.queryscope`.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from climrr import litquery, queryscope  # noqa: E402
from climrr.checksums import sha256_file  # noqa: E402
from climrr.manifest import verify_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402
from parse_literature_query import SCOPE_NOTE  # noqa: E402

QUERY_PATH = REPO_ROOT / "data" / "metadata" / "literature_query.txt"
PARSED_PATH = REPO_ROOT / "artifacts" / "literature" / "query_parsed.json"
PROTOTYPES_DIR = REPO_ROOT / "artifacts" / "phenomena" / "prototypes"
PILOT_SUBSET_PATH = REPO_ROOT / "docs" / "PILOT_SUBSET.md"
OUT_JSON = REPO_ROOT / "artifacts" / "literature" / "query_scope_coverage.json"
OUT_MD = REPO_ROOT / "docs" / "LITERATURE_QUERY_SCOPE.md"


class StaleParseError(RuntimeError):
    """query_parsed.json no longer matches a fresh parse of the pinned query."""


def load_structure(query_path: Path, parsed_path: Path) -> tuple[dict, dict, dict]:
    verified = verify_file(query_path)
    structure = litquery.extract_structure(query_path.read_bytes().decode("utf-8"))
    parsed = json.loads(parsed_path.read_text(encoding="utf-8"))
    if (
        parsed.get("source_sha256") != verified["sha256"]
        or parsed.get("hazard_groups") != structure["hazard_groups"]
        or parsed.get("context_terms") != structure["context_terms"]
    ):
        raise StaleParseError(
            f"{repo_relative(parsed_path)} does not match a fresh parse of the pinned "
            "query. Re-run scripts/parse_literature_query.py."
        )
    return verified, structure, parsed


def _cell(ids: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in ids) if ids else "—"


def render_markdown(result: dict) -> str:
    cov = result["coverage"]
    L: list[str] = []
    a = L.append
    a("# Literature query scope --- the pilot's vocabulary against the collection query")
    a("")
    a("*Generated by `scripts/query_scope_coverage.py` (M4-WP0, Phase D). Do not edit by hand;")
    a("re-run the script. Machine-readable twin:")
    a("[`../artifacts/literature/query_scope_coverage.json`](../artifacts/literature/query_scope_coverage.json).*")
    a("")
    a(f"> **{SCOPE_NOTE}**")
    a("")
    a("This is **query-scope coverage**, not corpus coverage. It compares strings the pilot")
    a("uses with strings the collection query contains. Every statement below is about the")
    a("query. None is about any paper in the corpus, and none says that the corpus does or")
    a("does not hold evidence about anything.")
    a("")
    a("## Inputs")
    a("")
    a("| Input | Path | SHA-256 |")
    a("| --- | --- | --- |")
    for item in result["inputs"]:
        a(f"| {item['role']} | `{item['path']}` | `{item['sha256']}` |")
    a("")
    s = result["query_counts"]
    a(f"The query parses as `{result['boolean_structure']}`: **{s['n_hazard_groups']} hazard")
    a(f"groups** holding {s['n_hazard_terms']} terms, and **{s['n_context_terms']} context terms** ---")
    a(f"{s['n_terms']} terms in all. Groups carry positional ids only; a group is referred to")
    a("below by its id and its first term, which is a quotation, not a name.")
    a("")
    a("*The work package that commissioned this document describes the first disjunction as")
    a(f"ten hazard groups. The deterministic parse finds {s['n_hazard_groups']}; the parse is reported as")
    a("found.*")
    a("")
    a("## Classification rule")
    a("")
    a("Each pilot string is compared **as a whole string** with every query term:")
    a("")
    a("- `exact_query_term` --- identical to a query term's text;")
    a("- `normalized_lexical_match` --- identical after normalization (curly quotes to straight,")
    a("  lower case, single spaces, trimmed; hyphens kept);")
    a("- `absent_from_query` --- neither.")
    a("")
    a("No substring, word, synonym or stem matching is done. The ruling's fourth category,")
    a("`inferred_conceptual_relationship`, is **defined and unused** --- the classifier cannot")
    a("emit it, and introducing it is a decision for a later package.")
    a("")
    a("## 1. Prototype concept terms represented in the query")
    a("")
    a("The `literature_probe.concept_terms` of each prototype record --- a design stub; no")
    a("retrieval was ever performed with them.")
    a("")
    a("| Prototype | Concept term | Classification | Matched query term |")
    a("| --- | --- | --- | --- |")
    for proto in cov["per_prototype"]:
        for row in proto["rows"]:
            a(f"| `{proto['record_id']}` | {row['term']} | `{row['classification']}` | {_cell(row['matched_term_ids'])} |")
    a("")
    a("| Prototype | exact | normalized | absent |")
    a("| --- | ---: | ---: | ---: |")
    for proto in cov["per_prototype"]:
        c = proto["counts"]
        a(f"| `{proto['record_id']}` | {c[queryscope.EXACT]} | {c[queryscope.NORMALIZED]} | {c[queryscope.ABSENT]} |")
    a("")
    a("## 2. Pilot family names")
    a("")
    a("Verbatim from the headings of `docs/PILOT_SUBSET.md`.")
    a("")
    a("| Family | Name | Classification | Matched query term |")
    a("| --- | --- | --- | --- |")
    for fam in cov["families"]:
        a(f"| {fam['family']} | {fam['name']} | `{fam['classification']}` | {_cell(fam['matched_term_ids'])} |")
    fc = cov["family_counts"]
    a("")
    a(f"Counts: exact {fc[queryscope.EXACT]}, normalized {fc[queryscope.NORMALIZED]}, absent {fc[queryscope.ABSENT]}.")
    a("A family name is a label this project wrote for a set of table columns; whole-string")
    a("comparison is expected to find few of them in a search query, and it does.")
    a("")
    a("## 3. Query hazard groups with no pilot counterpart")
    a("")
    a("A group has a pilot counterpart when one of its terms is the matched query term of an")
    a("`exact_query_term` or `normalized_lexical_match` row above. That is a statement about")
    a("which query strings equal which pilot strings, and nothing more.")
    a("")
    a("| Group | First term | Terms | Pilot counterpart |")
    a("| --- | --- | ---: | --- |")
    for g in cov["hazard_groups"]:
        a(f"| `{g['group_id']}` | {g['first_term']} | {g['n_terms']} | {_cell(g['pilot_matched_term_ids']) if g['has_pilot_counterpart'] else '**none**'} |")
    a("")
    outside = [g for g in cov["hazard_groups"] if not g["has_pilot_counterpart"]]
    a(f"**{len(outside)} of {len(cov['hazard_groups'])} query hazard groups have no pilot counterpart.** Their terms, verbatim:")
    a("")
    for g in outside:
        a(f"- `{g['group_id']}`: " + "; ".join(g["terms"]))
    a("")
    matched_ct = cov["context_terms_matched"]
    a(f"Context terms matched by any pilot string: {_cell(matched_ct)}.")
    a("")
    a("## 4. Dimensions absent from the query")
    a("")
    a("Each rule is applied to the normalized form of every one of the")
    a(f"{s['n_terms']} query terms. Source: `absence_checks` in")
    a("[`../artifacts/literature/query_parsed.json`](../artifacts/literature/query_parsed.json).")
    a("")
    a("| Rule | Dimension | Rule text | Hits | Result |")
    a("| --- | --- | --- | ---: | --- |")
    for check in result["absence_checks"]:
        a(f"| `{check['rule_id']}` | {check['dimension']} | {check['rule']} | {check['n_hits']} | **{check['result']}** |")
    a("")
    a("**No query term carries a scenario, a temporal horizon, a US state or postal code, or")
    a("the words county, tract, United States or USA.** \"No place name\" is verified **only**")
    a("against the lists in rules `AR-2` and `AR-3`: a place name on neither list --- a city, a")
    a("country other than the United States, a region --- would not be caught by them.")
    a("")
    a("This is a finding about how the collection query was written. The query does not")
    a("restrict by geography, scenario or horizon; it is not a finding about whether any")
    a("individual paper states one.")
    a("")
    a("## What this document does not say")
    a("")
    a("- It does not say the corpus holds evidence about heat index, fire weather, or any")
    a("  other concept. A query term admits a search result; it proves nothing about it.")
    a("- It does not assign any paper to a hazard group. No keyword-to-paper mapping exists,")
    a("  and the query cannot supply one.")
    a("- It does not rank, score, or relate any paper to any prototype.")
    a("")
    return "\n".join(L)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--query", type=Path, default=QUERY_PATH)
    parser.add_argument("--parsed", type=Path, default=PARSED_PATH)
    parser.add_argument("--prototypes", type=Path, default=PROTOTYPES_DIR)
    parser.add_argument("--pilot-subset", type=Path, default=PILOT_SUBSET_PATH)
    parser.add_argument("--out-json", type=Path, default=OUT_JSON)
    parser.add_argument("--out-md", type=Path, default=OUT_MD)
    args = parser.parse_args()

    try:
        verified, structure, parsed = load_structure(args.query, args.parsed)
    except StaleParseError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1

    probes = queryscope.load_probe_terms(args.prototypes)
    families = queryscope.load_pilot_families(args.pilot_subset)
    if len(families) != 4 or len(probes) != 3:
        print(f"FAIL: expected 3 prototypes and 4 families, found {len(probes)} and {len(families)}", file=sys.stderr)
        return 1

    cov = queryscope.coverage(structure, probes, families)
    inputs = [
        {"role": "collection query (pinned)", "path": repo_relative(args.query), "sha256": verified["sha256"]},
        {"role": "parsed query (derived)", "path": repo_relative(args.parsed), "sha256": sha256_file(args.parsed)},
        *[
            {"role": f"prototype {p['record_id']}", "path": repo_relative(p["path"]), "sha256": sha256_file(p["path"])}
            for p in probes
        ],
        {"role": "pilot families", "path": repo_relative(args.pilot_subset), "sha256": sha256_file(args.pilot_subset)},
    ]
    result = {
        "artifact": "query-scope coverage",
        "kind": "derived artifact --- regenerate with scripts/query_scope_coverage.py; never edit",
        "scope_note": SCOPE_NOTE,
        "naming": "query-scope coverage, not corpus coverage (ruling §3, action 4)",
        "inputs": inputs,
        "boolean_structure": parsed["boolean_structure"],
        "query_counts": parsed["counts"],
        "coverage": cov,
        "absence_checks": parsed["absence_checks"],
    }

    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    args.out_md.write_text(render_markdown(result), encoding="utf-8")

    emitted = {
        r["classification"]
        for r in [row for p in cov["per_prototype"] for row in p["rows"]] + cov["families"]
    }
    passed = emitted <= set(queryscope.EMITTABLE)
    for proto in cov["per_prototype"]:
        print(f"  {proto['record_id']:<12}: {proto['counts']}")
    print(f"  families    : {cov['family_counts']}")
    outside = [g["group_id"] for g in cov["hazard_groups"] if not g["has_pilot_counterpart"]]
    print(f"  groups with no pilot counterpart: {len(outside)} of {len(cov['hazard_groups'])}")
    print(f"  wrote       : {repo_relative(args.out_json)}, {repo_relative(args.out_md)}")

    record_path = write_run_record(
        "query_scope_coverage",
        result_summary={
            "per_prototype_counts": {p["record_id"]: p["counts"] for p in cov["per_prototype"]},
            "family_counts": cov["family_counts"],
            "hazard_groups_without_pilot_counterpart": outside,
            "context_terms_matched": cov["context_terms_matched"],
            "categories_emitted": sorted(emitted),
        },
        passed=passed,
        data_path=args.query,
        data_sha256=verified["sha256"],
        output_path=args.out_json,
        config_snapshot={i["role"]: i["path"] for i in inputs},
    )
    print(f"Run record: {repo_relative(record_path)}")
    print("PASS" if passed else "FAIL")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
