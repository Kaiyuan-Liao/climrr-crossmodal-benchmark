#!/usr/bin/env python3
"""M1-WP1 Phase D.1: extract the ClimRR data dictionary to tracked plain text.

Verifies the PDF against `data/manifest.json` (D-002 tracks it as authoritative
metadata, not literature), then extracts its text with the pinned `pypdf` and
writes `data/metadata/dictionary_extracted.txt`.

**The output is never hand-edited.** It is the evidence base every semantic
status in `artifacts/profiles/dictionary_coverage.json` cites by line number, so
a manual correction anywhere in it would silently invalidate every citation. If
the extraction is wrong, fix the extractor and regenerate; do not touch the file.

The header records the source PDF's SHA-256 and the exact extractor version, so
a citation can always be traced to the bytes and the code that produced it.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

import pypdf  # noqa: E402

from climrr.checksums import sha256_file  # noqa: E402
from climrr.manifest import ManifestMismatchError, verify_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

PDF_PATH = REPO_ROOT / "data" / "metadata" / "ClimRR_Metadata_and_Data_Dictionary.pdf"
MANIFEST_PATH = REPO_ROOT / "data" / "manifest.json"
OUT_PATH = REPO_ROOT / "data" / "metadata" / "dictionary_extracted.txt"

PAGE_MARKER = "=== PAGE {number} ==="


def extract(pdf_path: Path) -> tuple[list[str], int]:
    """Return (page texts, page count). Page order is the PDF's own order."""
    reader = pypdf.PdfReader(str(pdf_path))
    return [page.extract_text() or "" for page in reader.pages], len(reader.pages)


def render(pages: list[str], *, pdf_path: Path, pdf_sha256: str, pdf_bytes: int) -> str:
    header = [
        "# ClimRR Metadata and Data Dictionary --- machine-extracted text",
        "#",
        f"# source_pdf          : {repo_relative(pdf_path)}",
        f"# source_pdf_sha256   : {pdf_sha256}",
        f"# source_pdf_bytes    : {pdf_bytes}",
        f"# extractor           : pypdf {pypdf.__version__}",
        f"# extracted_utc       : {datetime.now(timezone.utc).isoformat()}",
        f"# pages               : {len(pages)}",
        "#",
        "# Generated by scripts/extract_dictionary_text.py. NEVER hand-edited:",
        "# every semantic status in artifacts/profiles/dictionary_coverage.json",
        "# cites this file by line number, so an edit here would invalidate the",
        "# citations without changing them. Regenerate instead.",
        "#",
        "# Page boundaries are marked; all other text and line breaks are as the",
        "# extractor produced them.",
        "",
    ]
    body: list[str] = []
    for number, text in enumerate(pages, start=1):
        body.append(PAGE_MARKER.format(number=number))
        body.extend(text.splitlines())
        body.append("")
    return "\n".join(header + body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pdf", type=Path, default=PDF_PATH)
    parser.add_argument("--manifest", type=Path, default=MANIFEST_PATH)
    parser.add_argument("--out", type=Path, default=OUT_PATH)
    args = parser.parse_args()

    try:
        verified = verify_file(args.pdf, args.manifest)
    except (ManifestMismatchError, KeyError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2
    print(f"Manifest check OK: {args.pdf.name} sha256={verified['sha256']}")

    pages, n_pages = extract(args.pdf)
    text = render(pages, pdf_path=args.pdf, pdf_sha256=verified["sha256"], pdf_bytes=verified["bytes"])
    args.out.write_text(text, encoding="utf-8")

    n_chars = sum(len(page) for page in pages)
    n_empty_pages = sum(1 for page in pages if not page.strip())
    n_lines = text.count("\n")

    print(f"  pages                     : {n_pages}")
    print(f"  pages with no text        : {n_empty_pages}")
    print(f"  extracted characters      : {n_chars}")
    print(f"  output lines              : {n_lines}")
    print(f"  output                    : {repo_relative(args.out)}")
    print(f"  output sha256             : {sha256_file(args.out)}")

    # Usability gate. An extraction that is mostly empty is not evidence, and
    # Phase D must stop rather than build statuses on top of it.
    passed = n_pages > 0 and n_empty_pages < n_pages and n_chars > 500
    record_path = write_run_record(
        "extract_dictionary_text",
        result_summary={
            "pdf_sha256": verified["sha256"],
            "pypdf_version": pypdf.__version__,
            "pages": n_pages,
            "pages_with_no_text": n_empty_pages,
            "extracted_characters": n_chars,
            "output_sha256": sha256_file(args.out),
        },
        passed=passed,
        data_path=args.pdf,
        data_sha256=verified["sha256"],
        output_path=args.out,
        config_snapshot={
            "pdf_path": repo_relative(args.pdf),
            "extractor": f"pypdf {pypdf.__version__}",
        },
    )
    print(f"Run record: {repo_relative(record_path)}")
    print("PASS" if passed else "FAIL: extraction is unusable; stop Phase D and report")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
