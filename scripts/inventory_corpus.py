#!/usr/bin/env python3
"""M4-WP0 Phase E: byte-level inventory of the external literature corpus.

Walks the folder configured as `literature_corpus_root` in the untracked
`config/local_paths.yaml`, hashes every file as raw bytes, and writes

- `artifacts/literature/corpus_manifest.json` and `.csv` --- one entry per file;
- `docs/LITERATURE_CORPUS_INVENTORY.md` --- a generated summary;
- the `external_corpora` block of `data/manifest.json` --- the corpus identity
  later packages verify against.

**First run freezes; every later run verifies.** If the manifest already
exists, the folder is re-walked and re-hashed and compared with it; nothing is
rewritten, and any difference in the path set or in any file's bytes fails the
run. See `climrr.corpus` for the read boundary and the id rule.

The corpus path never leaves the untracked config: the manifest records the
config key, the root folder's basename, and paths relative to the root.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr import corpus  # noqa: E402
from climrr.checksums import sha256_file  # noqa: E402
from climrr.paths import get as get_local_path  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

OUT_DIR = REPO_ROOT / "artifacts" / "literature"
MANIFEST_JSON = OUT_DIR / "corpus_manifest.json"
MANIFEST_CSV = OUT_DIR / "corpus_manifest.csv"
DOC_PATH = REPO_ROOT / "docs" / "LITERATURE_CORPUS_INVENTORY.md"
DATA_MANIFEST = REPO_ROOT / "data" / "manifest.json"

CORPUS_ID = "LITCORPUS-00"

ROOT_PROVENANCE = {
    "folder_name": "00",
    "supplied_by": "JL",
    "supplied_to": "Kaiyuan Liao",
    "received_by_project": "2026-09-28",
    "received_with": "data/metadata/literature_query.txt (the collection query), from the same person",
    "stated_collector": "JL (stated by the supplier)",
    "location": "external to the repository; the absolute path is held only in the untracked config/local_paths.yaml under literature_corpus_root",
    "tracked_in_git": False,
    "on_sophia": False,
    "complete_result_set": "unknown (Q21)",
}

OWNER_OBSERVATION = (
    "Kaiyuan Liao opened one file in the folder, before this inventory, and it "
    "appeared off-topic: about urban surface water in Wuhan. This is an "
    "observation from one file, reported by Kaiyuan, not a property of the "
    "corpus; which file it was is not recorded, and this inventory opened no "
    "file to check. Consequence: M4-WP1's deterministic sample should expect "
    "off-topic items."
)


def manifest_document(entries: list[dict], root_basename: str, inventory_utc: str) -> dict:
    return {
        "artifact": "literature corpus inventory manifest",
        "manifest_version": 1,
        "corpus_id": CORPUS_ID,
        "config_reference": corpus.CONFIG_REFERENCE,
        "root_basename": root_basename,
        "inventory_utc": inventory_utc,
        "read_policy": corpus.READ_POLICY,
        "id_rule": corpus.ID_RULE,
        "content_identity_sha256": corpus.content_identity(entries),
        "content_identity_rule": (
            "SHA-256 of one UTF-8 line 'relative_path<TAB>sha256<TAB>bytes<LF>' per "
            "entry, in item_id order"
        ),
        "summary": corpus.summarize(entries),
        "entries": entries,
    }


def csv_text(entries: list[dict]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=list(corpus.ENTRY_FIELDS), lineterminator="\n")
    writer.writeheader()
    for e in entries:
        writer.writerow({k: ("" if e[k] is None else e[k]) for k in corpus.ENTRY_FIELDS})
    return buf.getvalue()


def _n(x) -> str:
    return f"{x:,}" if isinstance(x, int) else str(x)


def render_markdown(doc: dict, manifest_sha: str, csv_sha: str) -> str:
    s = doc["summary"]
    L: list[str] = []
    a = L.append
    a("# Literature corpus inventory")
    a("")
    a("*Generated by `scripts/inventory_corpus.py` (M4-WP0, Phase E) from the frozen manifest.")
    a("Do not edit by hand. The manifest:")
    a("[`../artifacts/literature/corpus_manifest.json`](../artifacts/literature/corpus_manifest.json)")
    a("and [`.csv`](../artifacts/literature/corpus_manifest.csv).*")
    a("")
    a("> **Nothing in this document describes what any file contains.** Every file was read as")
    a("> raw bytes for its SHA-256 and size, and for nothing else. No file was decoded, parsed,")
    a("> rendered or opened in text mode; no filename was read for meaning. The corpus stays")
    a("> outside the repository.")
    a("")
    a("## Identity")
    a("")
    a("| | |")
    a("| --- | --- |")
    a(f"| Corpus id | `{doc['corpus_id']}` |")
    a(f"| Location | external --- `{doc['config_reference']}` (untracked); root folder named `{doc['root_basename']}` |")
    a(f"| Inventoried (UTC) | {doc['inventory_utc']} |")
    a(f"| Manifest SHA-256 (the corpus identity for later packages) | `{manifest_sha}` |")
    a(f"| Manifest CSV SHA-256 | `{csv_sha}` |")
    a(f"| Content identity SHA-256 (recomputable from the folder) | `{doc['content_identity_sha256']}` |")
    a("")
    a(f"Content identity rule: {doc['content_identity_rule']}. The manifest's SHA-256 pins the")
    a("frozen record; the content identity pins the folder, independent of timestamps and")
    a("formatting. Both are recorded in `data/manifest.json` under `external_corpora`.")
    a("")
    a("## Provenance of the root folder")
    a("")
    for k, v in ROOT_PROVENANCE.items():
        a(f"- **{k.replace('_', ' ')}:** {v if not isinstance(v, bool) else ('yes' if v else 'no')}")
    a("")
    a("Reported, not verified: who collected the folder, with which query, on which platform,")
    a("and whether it is the complete result set (Q19--Q21 in `docs/METADATA_QUESTIONS.md`).")
    a("Verified: the bytes of every file, as listed in the manifest.")
    a("")
    a("## Counts")
    a("")
    a("| | |")
    a("| --- | ---: |")
    a(f"| Files | {_n(s['n_entries'])} |")
    for acc, n in s["by_accessibility"].items():
        a(f"| Accessibility `{acc}` | {_n(n)} |")
    for ext, n in s["by_extension"].items():
        a(f"| Extension `{ext or '(none)'}` | {_n(n)} |")
    a(f"| Total bytes | {_n(s['total_bytes'])} |")
    a(f"| Smallest / median / largest file, bytes | {_n(s['min_bytes'])} / {_n(s['median_bytes'])} / {_n(s['max_bytes'])} |")
    a(f"| Zero-byte files | {_n(s['n_zero_byte'])} |")
    a(f"| Distinct SHA-256 values | {_n(s['n_unique_sha256'])} |")
    a(f"| Exact-byte duplicate groups | {_n(s['n_duplicate_groups'])} |")
    a(f"| Files in a duplicate group | {_n(s['n_items_in_duplicate_groups'])} |")
    a(f"| Redundant copies (files beyond the first in each group) | {_n(s['n_redundant_copies'])} |")
    a("")
    if s["zero_byte_item_ids"]:
        a("Zero-byte items: " + ", ".join(f"`{i}`" for i in s["zero_byte_item_ids"]) + ".")
        a("")
    a("## Exact-byte duplicates")
    a("")
    if s["duplicate_groups"]:
        a("Files sharing a SHA-256. **Identified, not removed** (ruling action 8): a later sample")
        a("should draw one item per group so a duplicate cannot count twice.")
        a("")
        a("| Group | Members | Bytes each | Item ids |")
        a("| --- | ---: | ---: | --- |")
        for g in s["duplicate_groups"]:
            a(f"| `{g['duplicate_group']}` | {g['n_members']} | {_n(g['bytes'])} | " + ", ".join(f"`{i}`" for i in g["item_ids"]) + " |")
    else:
        a("None: every file's SHA-256 is distinct.")
    a("")
    a("## An observation from one file, not a corpus property")
    a("")
    a(OWNER_OBSERVATION)
    a("")
    a("## Ids and reproducibility")
    a("")
    a(f"- {doc['id_rule']}")
    a(f"- {doc['read_policy']}")
    a("- Every entry carries at least relative path, extension, bytes and SHA-256, and a")
    a("  stable id suitable for a later bounded M4-WP1 sample drawn by rule.")
    a("- No entry carries a hazard group, a topic, a title, or any other reading. The collection")
    a("  query assigns nothing to any individual file.")
    a("")
    a("## Sophia")
    a("")
    a("The corpus is **not** on Sophia. A later package will transfer it out of band, with this")
    a("manifest as the verification gate --- the same pattern as `FullData.csv` (D-005). See")
    a("`docs/SOPHIA_RUNBOOK.md`.")
    a("")
    return "\n".join(L)


def update_data_manifest(doc: dict, manifest_sha: str, manifest_bytes: int, csv_sha: str) -> None:
    data = json.loads(DATA_MANIFEST.read_text(encoding="utf-8"))
    entry = {
        "corpus_id": CORPUS_ID,
        "role": "external literature corpus --- candidate papers collected by the query in data/metadata/literature_query.txt",
        "tracked_in_git": False,
        "config_key": corpus.CONFIG_KEY,
        "root_basename": doc["root_basename"],
        "inventory_manifest_path": repo_relative(MANIFEST_JSON),
        "inventory_manifest_sha256": manifest_sha,
        "inventory_manifest_bytes": manifest_bytes,
        "inventory_manifest_csv_path": repo_relative(MANIFEST_CSV),
        "inventory_manifest_csv_sha256": csv_sha,
        "content_identity_sha256": doc["content_identity_sha256"],
        "n_files": doc["summary"]["n_entries"],
        "total_bytes": doc["summary"]["total_bytes"],
        "inventory_utc": doc["inventory_utc"],
        "storage_policy": "never copied into the repository (ruling action 9); pinned by the inventory manifest's SHA-256, which later packages verify against",
        "interpretation_notes": "no interpretation assigned; no file has been opened for content",
        "provenance": ROOT_PROVENANCE,
        "decision_ref": "D-015",
    }
    corpora = [c for c in data.get("external_corpora", []) if c.get("corpus_id") != CORPUS_ID]
    data["external_corpora"] = corpora + [entry]
    DATA_MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()

    root = Path(get_local_path(corpus.CONFIG_KEY))
    fresh = corpus.scan(root)

    if MANIFEST_JSON.is_file():
        mode = "verify"
        doc = json.loads(MANIFEST_JSON.read_text(encoding="utf-8"))
        try:
            corpus.verify_against_frozen(fresh, doc["entries"])
            expected_ids = [f"{corpus.ID_PREFIX}{k:06d}" for k in range(1, len(doc["entries"]) + 1)]
            if [e["item_id"] for e in doc["entries"]] != expected_ids:
                raise corpus.CorpusChangedError("frozen manifest ids are not LIT-000001.. in order")
            if [e["relative_path"] for e in doc["entries"]] != [e["relative_path"] for e in fresh]:
                raise corpus.CorpusChangedError("frozen manifest is not in sorted-path order")
        except corpus.CorpusChangedError as exc:
            print(f"FAIL: {exc}", file=sys.stderr)
            return 1
    else:
        mode = "freeze"
        inventory_utc = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        entries = corpus.assign_ids_and_duplicates(fresh, inventory_utc)
        doc = manifest_document(entries, root.name, inventory_utc)
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        MANIFEST_JSON.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        MANIFEST_CSV.write_text(csv_text(entries), encoding="utf-8")

    manifest_sha = sha256_file(MANIFEST_JSON)
    csv_sha = sha256_file(MANIFEST_CSV)
    DOC_PATH.write_text(render_markdown(doc, manifest_sha, csv_sha), encoding="utf-8")
    update_data_manifest(doc, manifest_sha, MANIFEST_JSON.stat().st_size, csv_sha)

    s = doc["summary"]
    ok = s["by_accessibility"] == {"ok": s["n_entries"]}
    print(f"  mode               : {mode}")
    print(f"  files              : {s['n_entries']} {s['by_accessibility']}")
    print(f"  extensions         : {s['by_extension']}")
    print(f"  total bytes        : {s['total_bytes']}")
    print(f"  zero-byte          : {s['n_zero_byte']}")
    print(f"  duplicate groups   : {s['n_duplicate_groups']} ({s['n_items_in_duplicate_groups']} files)")
    print(f"  manifest sha256    : {manifest_sha}")
    print(f"  content identity   : {doc['content_identity_sha256']}")
    if not ok:
        print("ESCALATE: some entries are not accessibility 'ok' --- see the manifest", file=sys.stderr)

    record_path = write_run_record(
        "inventory_corpus",
        result_summary={
            "mode": mode,
            "corpus_id": CORPUS_ID,
            "n_files": s["n_entries"],
            "by_accessibility": s["by_accessibility"],
            "by_extension": s["by_extension"],
            "total_bytes": s["total_bytes"],
            "n_zero_byte": s["n_zero_byte"],
            "n_duplicate_groups": s["n_duplicate_groups"],
            "n_items_in_duplicate_groups": s["n_items_in_duplicate_groups"],
            "manifest_sha256": manifest_sha,
            "manifest_csv_sha256": csv_sha,
            "content_identity_sha256": doc["content_identity_sha256"],
            "inventory_utc": doc["inventory_utc"],
            "read_policy": corpus.READ_POLICY,
        },
        passed=ok,
        data_path=MANIFEST_JSON,
        data_sha256=manifest_sha,
        output_path=MANIFEST_JSON,
        config_snapshot={
            "corpus_root": corpus.CONFIG_REFERENCE,
            "root_basename": root.name,
        },
    )
    print(f"Run record: {repo_relative(record_path)}")
    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
