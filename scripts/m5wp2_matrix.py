#!/usr/bin/env python3
"""M5-WP2 step 2: run every adjudicated WP2 claim against the three prototypes, from the frozen inputs.

Verifies `artifacts/bridges/m5wp2_inputs.json` first (fail closed), then writes
`m5wp2_matrix.json`, `m5wp2_matrix.csv` and `docs/M5_WP2_COMPATIBILITY.md`,
once; a later run verifies byte equality. No QA.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr import compat, m5wp2  # noqa: E402
from climrr.checksums import sha256_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

DOC = REPO_ROOT / "docs" / "M5_WP2_COMPATIBILITY.md"
LABELS = {"P-CELL-1": "cell R106C361 (fire weather, summer)", "P-COUNTY-1": "Oklahoma, Stephens (fire weather, summer)",
          "P-STATE-1": "California (heat index, days above 105 °F)"}


def _write(path: Path, text: str) -> str:
    if path.exists():
        if path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"FAIL: {repo_relative(path)} differs from a rebuild")
        return "verified"
    path.write_text(text, encoding="utf-8")
    return "written"


def _md(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(rows: list[dict], summ: dict, frozen: dict) -> str:
    L = ["# M5-WP2 --- positive-case compatibility run", "",
         "**Generated by `scripts/m5wp2_matrix.py` from `artifacts/bridges/m5wp2_inputs.json`; do not edit by hand.** "
         "Every adjudicated claim of the four relevance-guided candidates (all evidence tiers, tier carried) against "
         "P-CELL-1, P-COUNTY-1 and **P-STATE-1 v2**, with revised C-2 (D-019). Deterministic rules only; no similarity, "
         "no model judgement. **No QA.** The frozen M5-WP1 inputs and matrix are untouched.", "",
         f"**{summ['n_pairs']} pairs** ({frozen['n_claims']} claims × {frozen['n_prototypes']} prototypes). "
         f"Candidate-bridge-eligible: **{summ['n_candidate_bridge_eligible']}**.", ""]
    if summ["n_candidate_bridge_eligible"] == 0:
        L += [f"> {m5wp2.BOUNDED_SENTENCE}", ""]
    L += ["## Per-dimension counts", "", "| Dimension | compatible | compatible_at_family_level | incompatible | not_evaluable |",
          "| --- | ---: | ---: | ---: | ---: |"]
    for d, v in summ["per_dimension"].items():
        L.append(f"| {d} | {v.get('compatible', 0)} | {v.get('compatible_at_family_level', 0)} | {v.get('incompatible', 0)} | {v.get('not_evaluable', 0)} |")
    L += ["", "Provisional relations: " + ", ".join(f"`{k}` {v}" for k, v in summ["relations"].items()) + ".",
          f"Incompatible by rule: {summ['incompatible_by_rule'] or 'none'}.", ""]
    elig = [r for r in rows if r["candidate_bridge_eligible"]]
    if elig:
        L += ["## Eligible pairs", ""]
        for r in elig:
            L += [f"### {r['pair_id']} (tier {r['evidence_tier']}; relation `{r['provisional_relation']}`)", "",
                  f"Claim: {_md(r['claim_text'])}", f"Evidence `{r['evidence']['json_path']}` [{r['evidence']['char_start']}, {r['evidence']['char_end']}): \"{_md(r['evidence']['evidence_text'])}\"", ""]
            L += [f"- {d}: **{j['status']}** ({j['rule_id']}, {j['reason']})" for d, j in r["judgments"].items()]
            L.append("")
        if any(r["evidence_tier"] == "C" for r in elig):
            L += [f"> {m5wp2.TIER_C_SENTENCE}", ""]
    rel = [r for r in rows if r["judgments"]["concept"]["status"] in ("compatible", compat.FAMILY_LEVEL)]
    L += ["## Pairs with a positive concept judgment", "",
          "| Pair | Tier | Concept | Matched term | Geography | Time | Scenario | Direction | Relation |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rel:
        j = r["judgments"]
        fm = j["concept"]["claim_value"].get("family_match", {})
        L.append(f"| {r['pair_id']} | {r['evidence_tier']} | {j['concept']['status']} ({j['concept']['rule_id']}) | "
                 f"\"{fm.get('matched_text', '')}\" [{fm.get('char_start')}, {fm.get('char_end')}) → {fm.get('family')} ({fm.get('concept_map_decision_id')}) | "
                 + " | ".join(f"{j[d]['status']} ({j[d]['rule_id']}: {j[d]['reason']})" for d in ("geography", "time", "scenario", "direction"))
                 + f" | `{r['provisional_relation']}` |")
    L += ["", "## Geography cases that name a prototype's state", "",
          "G-1 is exact equality of an `explicit` claim geography with the prototype label (`R106C361`; `Oklahoma, Stephens`; "
          "`California`). Every claim whose geography names Oklahoma or California, against every prototype:", "",
          "| Pair | Claim geography [tag] | Prototype label | Judgment | Why |", "| --- | --- | --- | --- | --- |"]
    for r in rows:
        g = r["judgments"]["geography"]
        raw = str(g["claim_value"].get("raw"))
        if "Oklahoma" in raw or "California" in raw:
            L.append(f"| {r['pair_id']} | {_md(raw)} [{g['claim_value'].get('tag')}] | {_md(g['prototype_value']['label'])} | "
                     f"{g['status']} ({g['rule_id']}) | {g['reason']} |")
    L += ["", "Readings of these rows: a different county in Oklahoma (`Dewey County, NW Oklahoma`) against the Stephens "
          "county prototype is `not_evaluable` --- a different label at the same level, neither compatible nor incompatible; "
          "a state-level or multi-state geography against a county or cell prototype is `not_evaluable` (different "
          "granularity); `California, Arizona and Nevada` against `California` is `not_evaluable` (a list of states is not "
          "the label); an `inferred` geography never reaches G-1.", "",
          "**G-2 list.** Only the committed M5-WP1 list is used (China, India, Tajikistan, Australia disjoint; `global`, "
          "`worldwide`, `Northwest Atlantic` not disjoint; US markers). Places outside the United States that are not on it "
          "--- Sardinia, France, Greece, Italy, Portugal, Spain, the Sahel, the Iberian Peninsula --- give `not_evaluable`, "
          "not `incompatible`. Extending the list was not authorized here.", "",
          "## Incompatible pairs", "", "| Pair | Tier | Rule | Claim value | Reason |", "| --- | --- | --- | --- | --- |"]
    for r in rows:
        for d, j in r["judgments"].items():
            if j["status"] == "incompatible":
                L.append(f"| {r['pair_id']} | {r['evidence_tier']} | {j['rule_id']} | {_md(j['claim_value'].get('raw'))} | {j['reason']} |")
    L += ["", "## Per prototype", "", "| Prototype | concept + | geography compatible | incompatible pairs | related_insufficient | uncertain |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for pid in ("P-CELL-1", "P-COUNTY-1", "P-STATE-1"):
        pr = [r for r in rows if r["prototype_id"] == pid]
        L.append(f"| {pid} --- {LABELS[pid]} | {sum(r['judgments']['concept']['status'] != 'not_evaluable' for r in pr)} | "
                 f"{sum(r['judgments']['geography']['status'] == 'compatible' for r in pr)} | {sum(r['n_incompatible'] > 0 for r in pr)} | "
                 f"{sum(r['provisional_relation'] == 'related_insufficient' for r in pr)} | {sum(r['provisional_relation'] == 'uncertain' for r in pr)} |")
    L += ["", "Relation rules, in precedence: " + "; ".join(f"`{k}`: {v}" for k, v in m5wp2.RELATION_RULES.items()) + ".", ""]
    return "\n".join(L) + "\n"


def main() -> int:
    try:
        frozen = m5wp2.verify_inputs()
    except m5wp2.FreezeError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    rows = m5wp2.run(frozen)
    if len(rows) != frozen["n_pairs"] or len({r["pair_id"] for r in rows}) != len(rows):
        print("FAIL: not every frozen pair evaluated exactly once", file=sys.stderr)
        return 1
    summ = m5wp2.summarize(rows)
    out = {"package": frozen["package"], "inputs_sha256": sha256_file(m5wp2.INPUTS_PATH), "rules": compat.ALL_RULES,
           "relation_rules": m5wp2.RELATION_RULES, "summary": summ, "rows": rows,
           "bounded_conclusion": m5wp2.BOUNDED_SENTENCE if summ["n_candidate_bridge_eligible"] == 0 else None}
    acts = {"json": _write(m5wp2.MATRIX_JSON, json.dumps(out, indent=2, ensure_ascii=False) + "\n"),
            "csv": _write(m5wp2.MATRIX_CSV, m5wp2.to_csv(rows)),
            "doc": _write(DOC, render(rows, summ, frozen))}
    print(f"  pairs {summ['n_pairs']}; eligible {summ['n_candidate_bridge_eligible']}; relations {summ['relations']}; {acts}")
    for d, v in summ["per_dimension"].items():
        print(f"   {d}: {v}")
    rec = write_run_record("m5wp2_matrix", result_summary={"actions": acts, "summary": {k: summ[k] for k in
                           ("n_pairs", "n_candidate_bridge_eligible", "relations", "per_dimension", "incompatible_by_rule")}},
                           passed=True, data_path=m5wp2.INPUTS_PATH, output_path=m5wp2.MATRIX_JSON,
                           config_snapshot={"inputs_sha256": sha256_file(m5wp2.INPUTS_PATH)})
    print(f"Run record: {repo_relative(rec)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
