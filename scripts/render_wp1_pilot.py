#!/usr/bin/env python3
"""M4-WP1 Phase D: render `docs/LITERATURE_WP1_PILOT.md` from the tracked records.

Every number, status and quotation in the document comes from
`artifacts/literature/wp1_sample.json`, `wp1_schema_observed.json`,
`wp1_claims_summary.json` and `wp1_claims/*.json`; nothing is typed by hand.
The document has no timestamp, so a re-run reproduces it byte for byte.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr.checksums import sha256_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

LIT = REPO_ROOT / "artifacts" / "literature"
OUT = REPO_ROOT / "docs" / "LITERATURE_WP1_PILOT.md"
DIMENSIONS = ("concept", "relation_or_direction", "geography", "temporal_frame", "scenario",
              "experimental_condition")
STATEMENT = "Ten items, deterministically sampled, for workflow validation; not representative of the corpus."


def load(name: str) -> dict:
    return json.loads((LIT / name).read_text(encoding="utf-8"))


def span(b: dict) -> str:
    return f"`{b['json_path']}` [{b['char_start']}, {b['char_end']}): “{b['evidence_text']}”"


def render() -> str:
    sample, schema, summary = load("wp1_sample.json"), load("wp1_schema_observed.json"), load("wp1_claims_summary.json")
    records = [load(f"wp1_claims/{i}.json") for i in sample["item_ids"]]
    t = summary["totals"]
    L: list[str] = []
    a = L.append
    a("# M4-WP1 --- literature ingestion and structured-claim pilot")
    a("")
    a("*Generated by `scripts/render_wp1_pilot.py` from the tracked records in")
    a("`artifacts/literature/`. Do not edit by hand.*")
    a("")
    a(f"> **{STATEMENT}**")
    a("")
    a("Claims are what the papers state, extracted by **manual reading by the EXECUTOR**")
    a(f"on {summary['extraction_date']} --- every file read completely, no model API, no embedding,")
    a("no search of other corpus files. No claim is related to any ClimRR prototype; that is")
    a("M5's question, not this pilot's.")
    a("")
    a(f"**Every claim is `single_reader_provisional`** "
      f"({t['by_claim_validation_status']['single_reader_provisional']} of {t['claims']}): one reader, not yet")
    a("independently confirmed (D-017). Status vocabulary: "
      + ", ".join(f"`{v}`" for v in summary["claim_validation_status_values"]) + ".")
    a("`scenario` is a climate or emissions scenario only; laboratory treatment levels are")
    a("recorded under `experimental_condition` (D-017).")
    a("")
    a("## The sample")
    a("")
    a(f"- Rule: {sample['rule']}")
    a(f"- Corpus manifest SHA-256: `{sample['corpus_manifest_sha256']}`")
    a(f"- Sample SHA-256: `{summary['sample_sha256']}` --- frozen and committed before any file was opened")
    a(f"- Items: {', '.join(f'`{i}`' for i in sample['item_ids'])}")
    a(f"- Duplicate skips: {'none' if not sample['skips'] else sample['skips']}")
    a("")
    a("## The JSON structure encountered")
    a("")
    a(f"All {schema['n_items']} files decoded as JSON objects ({schema['n_parse_failure']} parse failures). Every")
    a(f"file is **flat**: {schema['max_nesting_depth']} level, every value a string")
    a(f"({sum(schema['top_level_value_types'].values())} values, all of type string). Keys are section headings, lower-cased, and **no two")
    a(f"files share a key sequence** ({schema['n_distinct_top_level_key_sequences']} distinct sequences; no majority).")
    a("")
    a("| Key | Files |")
    a("| --- | ---: |")
    for k, n in sorted(schema["top_level_key_presence"].items(), key=lambda kv: (-kv[1], kv[0])):
        if n > 1:
            a(f"| `{k}` | {n} |")
    once = sum(1 for n in schema["top_level_key_presence"].values() if n == 1)
    a(f"| *{once} other keys* | 1 each |")
    a("")
    a("Irregularities found by reading, each recorded in the item's record rather than repaired:")
    a("a missing `title` key with a citation string in `abstract` (`LIT-001141`); `title` fields")
    a("holding a journal name (`LIT-001331`) and a page header (`LIT-001711`); whole passages")
    a("repeated inside a field; page-header fragments inside body text; and a place name stored")
    a("with a **combining** macron (`a` + U+0304), which is two code points.")
    a("")
    a("## The ten items")
    a("")
    a("| Item | Title (as stored, or where recovered) | Scope | Terminal status | Claims | Rejected / ambiguous |")
    a("| --- | --- | --- | --- | ---: | ---: |")
    for r in records:
        t_field = r["bibliographic"]["title"]
        title = t_field["value"]
        title = (title[:70] + "…") if len(title) > 70 else title
        title = title.replace("|", "\\|")
        if t_field["status"] == "recovered_from_other_field":
            title += f" *(recovered from `{t_field['evidence']['json_path']}`)*"
        a(f"| `{r['item_id']}` | {title} | `{r['scope_status']}` | `{r['terminal_status']}` | {len(r['claims'])} | {len(r['rejected_or_ambiguous'])} |")
    a("")
    a(f"**Totals:** {t['claims']} claims from {t['by_terminal_status']['claims_extracted']} items; "
      f"{t['claims_with_any_inferred_dimension']} claims carry an `inferred` dimension; "
      f"{t['rejected_or_ambiguous']} passages kept as rejected or ambiguous. "
      f"Span integrity: {summary['span_integrity_check']['spans_checked']} spans re-sliced from the "
      f"decoded source, all exact.")
    a("")
    a("Offsets are zero-based, half-open `[start, end)` Unicode code-point offsets into the JSON")
    a("string value after decoding and before any normalization.")
    a("")
    a("## Claims, item by item")
    a("")
    for r in records:
        a(f"### `{r['item_id']}` --- `{r['terminal_status']}`")
        a("")
        a(f"**Scope: `{r['scope_status']}`.** {r['scope_reason']}  ")
        a(f"Scope evidence: {span(r['scope_evidence'])}")
        a("")
        for c in r["claims"]:
            a(f"**{c['claim_id']}** ({c['claim_type']}; `{c['claim_validation_status']}`). {c['claim_text']}")
            a("")
            for d in DIMENSIONS:
                dim = c[d]
                extra = f" --- support {span(dim['support'])}" if "support" in dim else ""
                a(f"- {d.replace('_', ' ')}: {dim['value']} [`{dim['status']}`]{extra}")
            a(f"- evidence: {span(c['evidence'])}")
            if c.get("notes"):
                a(f"- note: {c['notes']}")
            a("")
        if r["rejected_or_ambiguous"]:
            a("Rejected or ambiguous:")
            a("")
            for x in r["rejected_or_ambiguous"]:
                a(f"- **{x['candidate_id']}** {span(x['evidence'])} --- {x['reason']}")
            a("")
        if r.get("notes"):
            a(f"*Item note:* {r['notes']}")
            a("")
    a("## What this document does not say")
    a("")
    a("- It does not say how many papers in the corpus are relevant. Ten items estimate nothing.")
    a("- It does not relate any claim to a ClimRR prototype, or call any claim supporting or")
    a("  contradicting.")
    a("- It does not generate or propose questions.")
    a("")
    return "\n".join(L)


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"  wrote {repo_relative(OUT)} sha256 {sha256_file(OUT)}")
    record = write_run_record(
        "render_wp1_pilot",
        result_summary={"doc_sha256": sha256_file(OUT),
                        "claims_summary_sha256": sha256_file(LIT / "wp1_claims_summary.json")},
        passed=True,
        data_path=LIT / "wp1_claims_summary.json",
        output_path=OUT,
        config_snapshot={"out": repo_relative(OUT)},
    )
    print(f"Run record: {repo_relative(record)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
