#!/usr/bin/env python3
"""Render `docs/LITERATURE_WP2_READING.md` from reader 1's WP2 records and the hit classification.

Reader-1 view only (Phase 1 of M4-WP2). Also computes three screens over the
recorded claims, deterministically:

* **US geography** --- the claim's geography value names the United States, a
  US state or DC, or the Southern Great Plains (`US_PLACE_TERMS`, boundary-aware
  via `climrr.conceptmap.find_term`), reported with its tag;
* **pilot concept term in the concept field** --- revised C-2's own search
  (`climrr.compat.family_term_hits`) over the concept value;
* **named scenario** --- `scenario` not `unknown`.

Prints counts; the document is regenerated, never hand-edited.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr import compat, conceptmap  # noqa: E402

LIT = REPO_ROOT / "artifacts" / "literature"
CLAIMS_DIR = LIT / "wp2_claims"
HITS = LIT / "wp2_hit_classification.json"
DOC = REPO_ROOT / "docs" / "LITERATURE_WP2_READING.md"
REPRESENTATIVENESS = "relevance-guided candidate sample, not representative"

US_STATES = ("Alabama", "Alaska", "Arizona", "Arkansas", "California", "Colorado", "Connecticut", "Delaware",
             "Florida", "Georgia", "Hawaii", "Idaho", "Illinois", "Indiana", "Iowa", "Kansas", "Kentucky",
             "Louisiana", "Maine", "Maryland", "Massachusetts", "Michigan", "Minnesota", "Mississippi", "Missouri",
             "Montana", "Nebraska", "Nevada", "New Hampshire", "New Jersey", "New Mexico", "New York",
             "North Carolina", "North Dakota", "Ohio", "Oklahoma", "Oregon", "Pennsylvania", "Rhode Island",
             "South Carolina", "South Dakota", "Tennessee", "Texas", "Utah", "Vermont", "Virginia", "Washington",
             "West Virginia", "Wisconsin", "Wyoming")
US_PLACE_TERMS = US_STATES + ("United States", "USA", "U.S.", "District of Columbia", "Southern Great Plains", "SGP")


def screens(claims: list[dict], entries: list[dict]) -> list[dict]:
    out = []
    for c in claims:
        geo = c["geography"]
        us = sorted({t for t in US_PLACE_TERMS if conceptmap.find_term(t, geo["value"])})
        fam = compat.family_term_hits(c["concept"]["value"], entries)
        out.append({"claim_id": c["claim_id"], "us_geography_terms": us, "geography_tag": geo["status"],
                    "pilot_concept_hits": [{k: h[k] for k in ("family", "surface_term", "char_start", "char_end")} for h in fam],
                    "scenario": c["scenario"]["value"]})
    return out


def _md(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def main() -> int:
    entries = conceptmap.load()
    recs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(CLAIMS_DIR.glob("LIT-*.json"))]
    hits = {i["item_id"]: i for i in json.loads(HITS.read_text(encoding="utf-8"))["items"]}
    allc = [c for r in recs for c in r["claims"]]
    sc = screens(allc, entries)
    n_us = sum(1 for s in sc if s["us_geography_terms"])
    n_us_explicit = sum(1 for s in sc if s["us_geography_terms"] and s["geography_tag"] == "explicit")
    n_pilot = sum(1 for s in sc if s["pilot_concept_hits"])
    n_scen = sum(1 for s in sc if s["scenario"] != "unknown")

    L = ["# M4-WP2 Phase 1 --- reader 1's reading of the four frozen candidates", "",
         f"**{REPRESENTATIVENESS.capitalize()}.** The four items are exactly the frozen M4-WP2 candidates "
         "(`LIT-000166`, `LIT-000519`, `LIT-001501`, `LIT-001536`); none was substituted or added. "
         "Generated by `scripts/render_wp2_reading.py`; do not edit by hand.", "",
         "**Reader 1 is the EXECUTOR, prototype-exposed.** It knew the frozen retrieval terms and each candidate's "
         "hit counts, but opened the hit list (paths and spans) only after its claims were built; hits are "
         "classified afterwards (below). Every claim is `single_reader_provisional`, **evidence tier C**, until "
         "the blind second reading (Phase 2) and adjudication (Phase 3). No compatibility has been run.", "",
         "## Summary", "",
         "| Item | Scope | Terminal | Claims | Hits | Substantive | Incidental | Different referent | Hit inside a promoted claim's evidence |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in recs:
        h = hits[r["item_id"]]
        L.append(f"| `{r['item_id']}` | {r['scope_status']} | {r['terminal_status']} | {len(r['claims'])} | {h['n_hits']} | "
                 f"{h['substantive']} | {h['incidental']} | {h['different_referent']} | {h['hits_inside_promoted_evidence']} |")
    L += ["", f"**Claims: {len(allc)}.** Claims whose geography names a US place: **{n_us}** "
          f"({n_us_explicit} explicit). Claims whose concept field contains an approved pilot family term "
          f"(revised C-2 search): **{n_pilot}**. Claims naming a climate/emissions scenario: **{n_scen}**.", ""]
    by_id = {s["claim_id"]: s for s in sc}
    for r in recs:
        h = hits[r["item_id"]]
        L += [f"## `{r['item_id']}` --- {_md(r['bibliographic']['title']['value'])}", "",
              f"**Scope:** {r['scope_status']} --- {_md(r['scope_reason'])}", "",
              f"Scope span (`{r['scope_evidence']['json_path']}` [{r['scope_evidence']['char_start']}, "
              f"{r['scope_evidence']['char_end']})): \"{_md(r['scope_evidence']['evidence_text'])}\"", ""]
        for c in r["claims"]:
            e = c["evidence"]
            s = by_id[c["claim_id"]]
            flags = []
            if s["us_geography_terms"]:
                flags.append(f"US geography ({c['geography']['status']})")
            if s["pilot_concept_hits"]:
                flags.append("pilot term in concept: " + ", ".join(x["surface_term"] for x in s["pilot_concept_hits"]))
            L += [f"- **{c['claim_id']}** ({c['claim_type']}; tier {c['evidence_tier']}) {_md(c['claim_text'])}"
                  + (f" _[{'; '.join(flags)}]_" if flags else ""),
                  f"  - evidence `{e['json_path']}` [{e['char_start']}, {e['char_end']}): \"{_md(e['evidence_text'])}\"",
                  "  - " + "; ".join(f"{d}: {_md(c[d]['value'])} [{c[d]['status']}]" for d in
                                     ("concept", "relation_or_direction", "geography", "temporal_frame", "scenario",
                                      "experimental_condition"))]
            if c.get("notes"):
                L.append(f"  - note: {_md(c['notes'])}")
        L += ["", "Considered and not promoted:", ""]
        L += [f"- `{x['candidate_id']}` \"{_md(x['evidence']['evidence_text'])}\" --- {_md(x['reason'])}" for x in r["rejected_or_ambiguous"]]
        L += ["", f"Retrieval hits, classified after reading: **{h['substantive']} substantive, {h['incidental']} incidental** "
              f"of {h['n_hits']}.", "", "| Term | Path | Span | Class | Reason | In promoted evidence |", "| --- | --- | --- | --- | --- | --- |"]
        for x in h["hits"]:
            L.append(f"| {x['matched_text']} | `{x['json_path']}` | [{x['char_start']}, {x['char_end']}) | {x['classification']}"
                     f"{'' if x['referent_matches_term'] else ' (different referent)'} | {_md(x['reason'])} | "
                     f"{', '.join(x['in_promoted_claim_evidence']) or '---'} |")
        L.append("")
    DOC.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  claims {len(allc)}; US geography {n_us} ({n_us_explicit} explicit); pilot concept term {n_pilot}; named scenario {n_scen}")
    for s in sc:
        if s["us_geography_terms"] or s["pilot_concept_hits"]:
            print(f"   {s['claim_id']}: us={s['us_geography_terms']} ({s['geography_tag']}) pilot={[x['surface_term'] for x in s['pilot_concept_hits']]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
