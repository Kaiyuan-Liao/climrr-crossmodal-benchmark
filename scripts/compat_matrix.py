#!/usr/bin/env python3
"""M5-WP1 Phase C: the 27 x 3 = 81-pair deterministic compatibility matrix.

Verifies the Phase A freeze first (fail closed), then evaluates every claim
against every prototype with the rules in `src/climrr/compat.py` and writes

- `artifacts/bridges/m5wp1_matrix.json` --- every row, every judgment, both values;
- `artifacts/bridges/m5wp1_matrix.csv`  --- the same rows, one line per pair;
- `docs/M5_WP1_COMPATIBILITY.md`        --- generated; do not edit by hand.

No output carries a timestamp, so a re-run reproduces all three byte for byte.
If any pair is compatible on all five dimensions the script still writes the
matrix, withholds the bounded conclusion, and exits 2: that result changes the
M4-WP2 argument and must be reported before anything is concluded from it.
"""

from __future__ import annotations

import csv
import io
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from climrr import compat  # noqa: E402
from climrr.checksums import sha256_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

MATRIX_JSON = compat.BRIDGES / "m5wp1_matrix.json"
MATRIX_CSV = compat.BRIDGES / "m5wp1_matrix.csv"
DOC = REPO_ROOT / "docs" / "M5_WP1_COMPATIBILITY.md"

BOUNDED_CONCLUSION = ("No fully compatible pair was found under the current deterministic rules "
                      "in this fixed provisional pilot set.")
STANDING = ("Machinery validation over `single_reader_provisional` claims (D-017). These rows are "
            "validation results, not accepted bridges, and they estimate nothing about the "
            "1,918-item corpus. The blind second reading (M4-WP1b) is pending.")
ABBREV = {"compatible": "comp", "incompatible": "INCOMP", "not_evaluable": "n/e"}


def _claim_side(j: dict) -> str:
    v = j["claim_value"]
    extra = ""
    if v.get("range"):
        extra = f" -> {v['range'][0]}-{v['range'][1]}"
    elif v.get("matched_term"):
        extra = f" -> matched '{v['matched_term']}'"
    elif v.get("canonical"):
        extra = f" -> {v['canonical']}"
    return f"[{v.get('tag')}] {v.get('raw')}{extra}"


def _proto_side(j: dict) -> str:
    v = j["prototype_value"]
    d = j["dimension"]
    if d == "geography":
        return f"{v['level']}: {v['label']} ({v['provenance_status']})"
    if d == "time":
        return f"future {v['future']}" if v["future"] else f"no year range in record: {v['raw']['future']!r}"
    return str(v.get("canonical"))


def write_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    head = ["pair_id", "claim_id", "claim_type", "is_background_citation", "claim_validation_status",
            "prototype_id", "all_compatible", "n_incompatible"]
    for d in compat.DIMENSIONS:
        head += [f"{d}_status", f"{d}_rule_id", f"{d}_claim_value", f"{d}_prototype_value", f"{d}_reason"]
    w.writerow(head)
    for r in rows:
        line = [r["pair_id"], r["claim_id"], r["claim_type"], r["is_background_citation"],
                r["claim_validation_status"], r["prototype_id"], r["all_compatible"], r["n_incompatible"]]
        for d in compat.DIMENSIONS:
            j = r["judgments"][d]
            line += [j["status"], j["rule_id"], _claim_side(j), _proto_side(j), j["reason"]]
        w.writerow(line)
    return buf.getvalue()


def render(rows: list[dict], summary: dict, inputs_sha: str, geo_sha: str) -> str:
    L: list[str] = []
    a = L.append
    a("# M5-WP1 --- deterministic compatibility matrix, 27 claims x 3 prototypes")
    a("")
    a("*Generated by `scripts/compat_matrix.py` from `artifacts/bridges/m5wp1_matrix.json`.")
    a("Do not edit by hand.*")
    a("")
    a(f"> **{STANDING}**")
    a("")
    a("No semantic similarity, embedding or model judgement was used. A dimension is")
    a("`compatible` or `incompatible` only where a named rule below decides it; everywhere")
    a("else it is `not_evaluable`. `unknown` on either side is always `not_evaluable`.")
    a("**Different is not incompatible:** incompatibility needs explicit disjointness under a")
    a("named rule.")
    a("")
    a("## Inputs")
    a("")
    a(f"- Frozen inputs: `artifacts/bridges/m5wp1_inputs.json`, SHA-256 `{inputs_sha}`")
    a(f"- Geography list (G-2): `config/geo_disjoint_list.yaml`, SHA-256 `{geo_sha}`")
    a(f"- Pairs: **{summary['n_pairs']}** --- every claim against every prototype, none dropped")
    a(f"- Pairs whose claim is a `background_citation`: {summary['n_background_citation_pairs']}"
      " (kept, and flagged in every row)")
    a("- **Approved concept mappings: none exist in the repository.** C-1 can therefore match")
    a("  only a claim concept that already *is* a canonical ID string.")
    a("")
    a("## Rules")
    a("")
    a("| Rule | Statement |")
    a("| --- | --- |")
    for k, v in compat.RULES.items():
        a(f"| `{k}` | {v.replace('|', '/')} |")
    a("")
    a("## Counts per dimension (all 81 pairs)")
    a("")
    a("| Dimension | compatible | incompatible | not_evaluable |")
    a("| --- | ---: | ---: | ---: |")
    for d in compat.DIMENSIONS:
        c = summary["per_dimension"][d]
        a(f"| {d} | {c['compatible']} | {c['incompatible']} | {c['not_evaluable']} |")
    a("")
    a("## Counts per prototype")
    a("")
    a("Each cell: compatible / incompatible / not_evaluable.")
    a("")
    a("| Prototype | " + " | ".join(compat.DIMENSIONS) + " |")
    a("| --- |" + " --- |" * len(compat.DIMENSIONS))
    for pid, dims in summary["per_prototype"].items():
        cells = [f"{dims[d]['compatible']} / {dims[d]['incompatible']} / {dims[d]['not_evaluable']}"
                 for d in compat.DIMENSIONS]
        a(f"| `{pid}` | " + " | ".join(cells) + " |")
    a("")
    a("## Why: reason counts per dimension")
    a("")
    a("| Dimension | Status | Rule | Reason | Pairs |")
    a("| --- | --- | --- | --- | ---: |")
    for d in compat.DIMENSIONS:
        tally: dict[tuple, int] = {}
        for r in rows:
            j = r["judgments"][d]
            key = (j["status"], j["rule_id"], j["reason"])
            tally[key] = tally.get(key, 0) + 1
        for (s, rule, reason), n in sorted(tally.items()):
            a(f"| {d} | {s} | `{rule}` | `{reason}` | {n} |")
    a("")
    a("## Outcome")
    a("")
    a(f"- Pairs compatible on all five dimensions: **{summary['n_all_compatible']}**")
    a(f"- Pairs with at least one `incompatible`: **{summary['n_pairs_with_any_incompatible']}**")
    rules = ", ".join(f"`{k}` {v}" for k, v in summary["incompatible_by_rule"].items()) or "none"
    a(f"- `incompatible` judgments by rule: {rules}")
    a("")
    if summary["n_all_compatible"] == 0:
        a(f"**{BOUNDED_CONCLUSION}**")
        a("")
        a("That is the whole conclusion. It is not a statement about the corpus, and it is")
        a("not yet a statement about these ten papers: the claims are single-reader")
        a("provisional until M4-WP1b closes.")
    else:
        a(f"**{summary['n_all_compatible']} pair(s) are compatible on all five dimensions:** "
          + ", ".join(f"`{p}`" for p in summary["all_compatible_pair_ids"]) + ".")
        a("")
        a("**Conclusion withheld and escalated** (work-package stop condition).")
    a("")
    a("## The full matrix")
    a("")
    a("`comp` compatible, `INCOMP` incompatible, `n/e` not_evaluable; the deciding rule in")
    a("brackets. Every claim is `single_reader_provisional`. Both compared values and the")
    a("reason for every cell are in the JSON and CSV.")
    a("")
    a("| Pair | Type | Concept | Geography | Time | Scenario | Direction |")
    a("| --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        typ = "**background_citation**" if r["is_background_citation"] else r["claim_type"]
        cells = [f"{ABBREV[r['judgments'][d]['status']]} ({r['judgments'][d]['rule_id']})" for d in compat.DIMENSIONS]
        a(f"| `{r['claim_id']}` x `{r['prototype_id']}` | {typ} | " + " | ".join(cells) + " |")
    a("")
    return "\n".join(L)


def main() -> int:
    try:
        frozen = compat.verify_inputs()
    except compat.FreezeError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    inputs_sha = sha256_file(compat.INPUTS_PATH)
    geo_sha = sha256_file(compat.GEO_LIST_PATH)
    claims, protos = compat.load_frozen_claims_and_prototypes(frozen)
    rows = compat.build_matrix(claims, protos, compat.load_geo_list())
    summary = compat.summarize(rows)
    if summary["n_pairs"] != frozen["n_pairs"] or len({r["pair_id"] for r in rows}) != len(rows):
        print("FAIL: matrix does not hold every frozen pair exactly once", file=sys.stderr)
        return 1

    matrix = {
        "package": "M5-WP1",
        "standing": STANDING,
        "inputs_sha256": inputs_sha,
        "geo_disjoint_list_sha256": geo_sha,
        "statuses": list(compat.STATUSES),
        "dimensions": list(compat.DIMENSIONS),
        "rules": compat.RULES,
        "approved_concept_mappings": compat.APPROVED_CONCEPT_MAPPINGS,
        "summary": summary,
        "bounded_conclusion": BOUNDED_CONCLUSION if summary["n_all_compatible"] == 0 else None,
        "rows": rows,
    }
    MATRIX_JSON.write_text(json.dumps(matrix, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    MATRIX_CSV.write_text(write_csv(rows), encoding="utf-8")
    DOC.write_text(render(rows, summary, inputs_sha, geo_sha), encoding="utf-8")

    for d in compat.DIMENSIONS:
        print(f"  {d:<10} {summary['per_dimension'][d]}")
    print(f"  all-compatible: {summary['n_all_compatible']}; with any incompatible: "
          f"{summary['n_pairs_with_any_incompatible']}; by rule: {summary['incompatible_by_rule']}")
    stop = summary["n_all_compatible"] > 0
    record = write_run_record(
        "compat_matrix",
        result_summary={"n_pairs": summary["n_pairs"], "n_all_compatible": summary["n_all_compatible"],
                        "n_pairs_with_any_incompatible": summary["n_pairs_with_any_incompatible"],
                        "incompatible_by_rule": summary["incompatible_by_rule"],
                        "per_dimension": summary["per_dimension"],
                        "matrix_json_sha256": sha256_file(MATRIX_JSON),
                        "matrix_csv_sha256": sha256_file(MATRIX_CSV),
                        "doc_sha256": sha256_file(DOC),
                        "stop_all_compatible_found": stop},
        passed=not stop,
        data_path=compat.INPUTS_PATH,
        data_sha256=inputs_sha,
        output_path=MATRIX_JSON,
        config_snapshot={"geo_disjoint_list": "config/geo_disjoint_list.yaml", "geo_disjoint_list_sha256": geo_sha,
                         "t2_cutoff_year": compat.T2_CUTOFF_YEAR,
                         "approved_concept_mappings": compat.APPROVED_CONCEPT_MAPPINGS},
    )
    print(f"Run record: {repo_relative(record)}")
    if stop:
        print("STOP: a pair is compatible on all five dimensions; conclusion withheld. Escalate.", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
