#!/usr/bin/env python3
"""Track B Stage 2a: build the dictionary concept inventory (diagnostic).

Verifies the dictionary PDF against `data/manifest.json` (D-002), extracts its
text page by page with the pinned `pypdf`, and writes

* `data/metadata/dictionary_concepts.yaml` --- one entry per output quantity the
  dictionary's narrative describes (measure level, D-026), every string an
  exact slice of one page's extracted text;
* `docs/DICTIONARY_CONCEPTS.md` --- generated counts and method.

The concept rules live in `src/climrr/dictconcepts.py`. The YAML is byte-
deterministic, so rerunning reproduces the hash pinned in the manifest. It
assigns no meaning to any CSV column; existing M1 statuses are unchanged; index
117 remains unlabeled.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

import pypdf  # noqa: E402

from climrr import dictconcepts as dc  # noqa: E402
from climrr.checksums import sha256_file  # noqa: E402
from climrr.manifest import ManifestMismatchError, verify_file  # noqa: E402
from climrr.paths import repo_relative  # noqa: E402
from climrr.runrecord import write_run_record  # noqa: E402

PDF_PATH = REPO_ROOT / "data" / "metadata" / "ClimRR_Metadata_and_Data_Dictionary.pdf"
MANIFEST_PATH = REPO_ROOT / "data" / "manifest.json"
COVERAGE_PATH = REPO_ROOT / "artifacts" / "profiles" / "dictionary_coverage.json"
RESOLUTIONS_PATH = REPO_ROOT / "data" / "metadata" / "resolutions.yaml"
OUT_PATH = REPO_ROOT / "data" / "metadata" / "dictionary_concepts.yaml"
DOC_PATH = REPO_ROOT / "docs" / "DICTIONARY_CONCEPTS.md"


def render_doc(concepts: list[dict], header: dict, yaml_sha: str) -> str:
    n = len(concepts)
    n_listed = sum(c["status"] == "listed_only" for c in concepts)
    rows = "\n".join(
        f"| `{c['id']}` | {c['name']} | {c['page'] if c['page'] is not None else '---'} "
        f"| {c['units'] or '---'} | {(c['metric_or_threshold'] or '---').replace(chr(10), ' ')} "
        f"| {c['scenario_or_horizon'] or '---'} | `{c['status']}` |"
        for c in concepts
    )
    return f"""# Dictionary concepts --- Stage 2a inventory

**GENERATED by `scripts/build_dictionary_inventory.py`. Do not edit; regenerate.**

{dc.STATEMENT}

Authorized by `docs/M4_WP3_WORKING_CORPUS_STAGE2_GUIDANCE_RULING.md` (D-025, Track B,
Stage 2a, criteria 23--25). Granularity: D-026.

## Counts

| | |
| --- | --- |
| Concepts | **{n}** |
| `dictionary_described` | **{n - n_listed}** |
| `listed_only` | **{n_listed}** |
| `family_hint` non-null | **0** (always null; family assignment is a GUIDANCE decision) |
| Concepts with non-empty `verified_columns` | **{sum(bool(c['verified_columns']) for c in concepts)}** |
| `data/metadata/dictionary_concepts.yaml` SHA-256 | `{yaml_sha}` |

## Method

- **Source:** `{header['source_pdf']}` only (D-002), SHA-256 `{header['source_pdf_sha256']}`,
  verified against `data/manifest.json` before extraction.
- **Extractor:** `{header['extractor']}`, page by page (`PdfReader(...).pages[i].extract_text()`).
  `char_span` is zero-based, half-open, into the extracted text of `page`; the SHA-256 of
  every page text used is in the YAML header (`page_text_sha256`), so a span can be checked
  against the exact text it indexes.
- **Unit of inventory --- measure level (D-026).** One concept per ClimRR output quantity the
  narrative (pp. 4--12) describes. Two quantities the dictionary describes in one passage
  (maximum and minimum daily temperature; HDD and CDD) stay one concept. The heat index is
  split as the dictionary enumerates it, the four thresholds as four concepts (p. 12: "the 6
  variables"). Methodology sections (Climate Scenarios, Downscaled Climate Models, Ensemble
  Means, Components of the FWI) are excluded; the variable lists on pp. 4 and 13 are not
  separate concepts. Field-table rows (pp. 13--19) are not concepts.
- **Name:** the dictionary's own heading or enumerated label for the quantity, verbatim, with
  its own page and span (`name_source`). Two exceptions, both verbatim: the seasonal-average
  FWI concept takes the section heading "Fire Weather Index", because its sub-heading
  "Calculating Seasonal Averages" names only a procedure; the four threshold concepts take
  the per-threshold wording of the p. 18 field table ("Number of Summer days with daily max
  heat index above 105 F"), because the narrative's label covers all four at once.
- **Passage:** a minimal verbatim window on one page --- from the first sentence naming the
  quantity produced to the sentence completing its definition (including the units sentence
  where units are stated). The four threshold concepts share the p. 11 passage of item 3,
  which the page break cuts mid-sentence; its continuation on p. 12 is not included.
- **Units / threshold / scenario:** filled only when stated inside the passage (the threshold
  concepts: inside the name); otherwise null. So the p. 12 statement of the heat-index
  periods, which lies outside the heat-index windows, is not propagated, and temperature
  units, stated only in the field tables, are null.
- **`verified_columns`:** only columns already `verified_from_dictionary` whose resolution
  record cites the passage. No resolution record can assign that status
  (`data/metadata/resolutions.yaml`, rule 1) and none of the 21 verified columns references
  one, so every list is empty.
- **No inference from CSV headers.** No column name is read; no column status changes.

## Inventory

| Id | Name | Page | Units | Metric / threshold | Scenario / horizon | Status |
| --- | --- | --- | --- | --- | --- | --- |
{rows}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pdf", type=Path, default=PDF_PATH)
    parser.add_argument("--manifest", type=Path, default=MANIFEST_PATH)
    parser.add_argument("--out", type=Path, default=OUT_PATH)
    parser.add_argument("--doc", type=Path, default=DOC_PATH)
    args = parser.parse_args()

    try:
        verified_pdf = verify_file(args.pdf, args.manifest)
    except (ManifestMismatchError, KeyError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2

    pages = dc.extract_pages(args.pdf)
    verified = dc.load_verified(COVERAGE_PATH, RESOLUTIONS_PATH)
    concepts = dc.build_concepts(pages, verified)

    used = sorted({c["page"] for c in concepts if c["page"]} | {c["name_source"]["page"] for c in concepts})
    header = {
        "schema_version": dc.SCHEMA_VERSION,
        "statement": dc.STATEMENT,
        "authorized_by": "docs/M4_WP3_WORKING_CORPUS_STAGE2_GUIDANCE_RULING.md (D-025); granularity D-026",
        "source_pdf": repo_relative(args.pdf),
        "source_pdf_sha256": verified_pdf["sha256"],
        "extractor": f"pypdf {pypdf.__version__}",
        "char_span_convention": "zero-based, half-open, into the extracted text of the page",
        "page_text_sha256": {p: dc.sha256_text(pages[p - 1]) for p in used},
    }
    args.out.write_text(dc.render_yaml(concepts, header=header), encoding="utf-8")
    yaml_sha = sha256_file(args.out)
    args.doc.write_text(render_doc(concepts, header, yaml_sha), encoding="utf-8")

    n_listed = sum(c["status"] == "listed_only" for c in concepts)
    print(f"concepts: {len(concepts)}  listed_only: {n_listed}")
    for c in concepts:
        print(f"  {c['id']}  p{c['page']}  {c['name']}")
    print(f"inventory sha256: {yaml_sha}")

    passed = all(pages[c["page"] - 1][slice(*c["char_span"])] == c["passage"]
                 for c in concepts if c["passage"] is not None)
    record = write_run_record(
        "build_dictionary_inventory",
        result_summary={
            "n_concepts": len(concepts),
            "n_listed_only": n_listed,
            "n_with_verified_columns": sum(bool(c["verified_columns"]) for c in concepts),
            "inventory_sha256": yaml_sha,
            "pypdf_version": pypdf.__version__,
        },
        passed=passed,
        data_path=args.pdf,
        data_sha256=verified_pdf["sha256"],
        output_path=args.out,
        config_snapshot={"pdf_path": repo_relative(args.pdf), "extractor": f"pypdf {pypdf.__version__}",
                         "granularity": "measure level (D-026)"},
    )
    print(f"Run record: {repo_relative(record)}")
    print("PASS" if passed else "FAIL: a passage does not re-slice from its page")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
