from climrr.paths import REPO_ROOT

EXAMPLES_DIR = REPO_ROOT / "artifacts" / "examples"
DATA_PATH = REPO_ROOT / "data" / "raw" / "FullData.csv"

#: Words that describe how large a value is. The presentation may not use them:
#: the mentor is being asked what a field means, not invited to agree that a
#: number is big. `extreme` is on the list even though the dictionary uses it as
#: an FWI class name --- no pilot column carries those classes (Q8).
MAGNITUDE_WORDS = (
    "significant",
    "significantly",
    "dramatic",
    "dramatically",
    "hot",
    "hotter",
    "hottest",
    "dangerous",
    "dangerously",
    "severe",
    "extreme",
    "extremely",
    "alarming",
    "unprecedented",
    "sharp",
    "sharply",
    "striking",
    "worrying",
    "massive",
)

#: Wordings that would read a Fire Weather Index as a fire, or a modeled
#: baseline as an observation. None may appear anywhere in a record.
FORBIDDEN_PHRASES = (
    "wildfire occurred",
    "wildfires occurred",
    "fire occurred",
    "ignition probability",
    "risk of fire",
    "fire risk",
    "observed historical",
    "historical observation",
    "was recorded at",
    "was measured",
    "actually happened",
)

#: Fire vocabulary a record may use **only inside a denial**. The records have
#: to be able to say "this is not a burned area"; what they may not do is say it
#: is one. Each occurrence must sit within this many characters after a "not".
FIRE_VOCABULARY = ("burned area", "ignition", "wildfire,")
DENIAL_WINDOW = 80


def examples() -> list[dict]:
    paths = sorted(EXAMPLES_DIR.glob("example_*.json"))
    return [json.loads(path.read_text(encoding="utf-8")) for path in paths]


