"""Example records: the raw layer round-trips, and no inference passes as fact.

Four properties matter more than the rest, and D-011 names three of them:

* the `raw` block is the file, byte for byte, so the record can always be
  checked against the source rather than believed;
* no clause resting on an inferred attribute reaches the mentor without a
  `[provisional: ...]` label;
* changing an IC-record changes the presentation, so the reasoning is genuinely
  what the prose is generated from and not decoration beside it;
* a blank is rendered "no value in this file" and never as a number.

The synthetic fixtures below stand in for the 275-column table wherever the
property does not need the real one. The tests that do need it read the tracked
artifacts, which are regenerated by `scripts/build_examples.py`.
"""

