def test_select_rows_returns_the_first_row_matching_each_rule(tmp_path):
    """A tiny table where the answers can be read off by eye."""
    header = ",".join(f"c{index}" for index in range(276))

    def row(oid: str, geoid: str, blank_at: int | None = None) -> str:
        cells = [str(index) for index in range(276)]
        cells[0] = oid
        cells[1] = f"R{oid}C1"
        cells[109] = geoid
        if blank_at is not None:
            cells[blank_at] = ""
        return ",".join(cells)

    path = tmp_path / "tiny.csv"
    path.write_text(
        "\n".join(
            [
                header,
                row("1", "40137000902", blank_at=238),  # blank -> R-C
                row("2", "40137000903"),  # complete, no leading zero -> R-A
                row("3", "06071010300"),  # complete, leading zero -> R-B
                row("4", "06071010301"),  # a later match for both, ignored
            ]
        )
        + "\n",
        encoding="utf-8",
        newline="",
    )

    found = select_rows(path)
    assert found["R-A"]["ordinal"] == 1
    assert found["R-B"]["ordinal"] == 2
    assert found["R-C"]["ordinal"] == 0


