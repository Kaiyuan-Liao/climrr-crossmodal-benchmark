def test_a_blank_is_rendered_as_no_value_and_never_as_a_number(built):
    blank_records = [
        record
        for record in built
        if any(item["value"] == "" for item in record["raw"])
    ]
    assert blank_records, "R-C must select a row with at least one blank pilot column"

    for record in blank_records:
        text = record["presentation"]["text"]
        for item in record["raw"]:
            if item["value"] != "":
                continue
            line = column_line(text, item["index"])
