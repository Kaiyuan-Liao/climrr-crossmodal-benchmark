def display_source(item: dict) -> str:
    """`polished` when the item's polish event passed (the text is the rewrite), else `original`."""
    ev = next((h for h in reversed(item["review"]["history"]) if h.get("event") == "polish"), None)
    return "polished" if ev and ev["status"] == "polished" else "original"


def display_text(item: dict) -> dict:
    """{prompt, answer} a reviewer sees, checked against the polish event: the rewrite if polished, else the original."""
    ev = next(h for h in reversed(item["review"]["history"]) if h.get("event") == "polish")
    want = ev["rewrite"] if ev["status"] == "polished" else ev["pre_polish"]
    got = {"prompt": item["prompt"], "answer": item["reference_answer"]["integrated"]}
    _check(got == want, f"{item['item_id']}: the item text is not its display text")
    return got


def human_review_item(item: dict, at: str) -> dict:
    """The D-033 lifecycle step deterministic_pass -> human_review, recording display_source; nothing else changes."""
    _check(item["review"]["status"] == "deterministic_pass", f"{item['item_id']}: status {item['review']['status']}")
    x = copy.deepcopy(item)
    x["review"].update(status="human_review", kaiyuan_disposition=None, mentor_disposition=None, final_frozen=None)
    x["review"]["history"].append({"event": "human_review", "from_status": "deterministic_pass", "decision": "D-033", "at": at,
                                   "by": INGEST_BY, "display_source": display_source(item), "note": HUMAN_REVIEW_NOTE})
    display_text(x)
    return x


def write_items(src: Path, items: list[dict], at: str) -> list[dict]:
    """`items/<item_id>.json`: every item = polish-run record + human_review."""
    schema, pitems, out = bi.load_schema(), read_polish_items(src), []
    for it in sorted(items, key=lambda x: x["item_id"]):
        sid = it["review"]["history"][0]["seed_id"]
        x = human_review_item(pitems[sid], at)
        errs = bi.schema_errors(x, schema) + bi.consistency_errors(x)
        _check(not errs, f"{x['item_id']}: invalid: {errs}")
        path = ITEMS_DIR / f"{x['item_id']}.json"
        r2.write_json(path, x)
        out.append({"item_id": x["item_id"], "seed_id": sid, "path": path.relative_to(ART).as_posix(), "sha256": sha256_file(path),
                    "status": x["review"]["status"], "history": [h["event"] for h in x["review"]["history"]],
                    "display_source": display_source(x), "schema_valid": True, "consistency_errors": []})
    return out


